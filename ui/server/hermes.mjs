// POST /vault/ask -- the desktop widget's question surface.
//
// NOT under /admin/, and not bearer-only: the widget is a native client that
// sends no Origin header, which selects the bearer channel, but an allowlisted
// page asking a question is the same trust level as /lane/local. What it is NOT
// is public -- authorize() still has to return a channel.
//
// BUFFERED JSON, NOT SSE. Deliberately: the answer is two sentences composed
// from at most 25 short claims, so streaming would add a protocol for no
// perceptible latency win and give the boundary a second shape to defend.
//
// The response is exactly {text, sources, usedRows}. `sources` is source NAMES
// only. A row object there would put the owner's verbatim words into a client
// that is outside the corpus boundary, which is the one thing this whole layer
// exists to prevent.
const VAULT_ASK_FIELDS = Object.freeze(['utterance']);
// VOICE-PLAN names 2000. Refused rather than truncated: a silently shortened
// question gets answered as if it were the whole question, and the asker never
// learns which half was dropped.
const MAX_UTTERANCE = 2000;

// The spine (contacts) lives in the connectors' state.db, a different file
// from the context store. Opened read-only, per call, only when a person
// search actually fires — the graph build is ~1s and not worth holding a
// handle for questions that are not person-searches. Returns null on any
// error or a non-match, so the ask route falls through unharmed.
function tryPersonSearch(db, question) {
  let state = null;
  try {
    const statePath = join(homedir(), '.hazlie', 'connectors', 'state.db');
    state = existsSync(statePath) ? new DatabaseSync(`file:${statePath}?mode=ro`, { readOnly: true }) : null;
    return answerPersonSearch(db, state, question, { owner: loadOwner() });
  } catch {
    return null;
  } finally {
    try {
      state?.close();
    } catch {}
  }
}

// The People-popup "initialize search" backend. Opens the spine read-only (like
// tryPersonSearch) and the owner's decisions store read-write, runs `fn`, and
// always closes both — even on throw — so a build never leaks a handle. The
// context db (the main store) is the caller's already-open handle. Errors
// propagate: unlike the ask-path helpers, these are explicit routes the widget
// invoked, so a failure should surface as a 500, not a silent null.
function withPeopleDbs(db, fn) {
  let state = null;
  let resDb = null;
  try {
    const statePath = join(homedir(), '.hazlie', 'connectors', 'state.db');
    state = existsSync(statePath) ? new DatabaseSync(`file:${statePath}?mode=ro`, { readOnly: true }) : null;
    resDb = openResolutionsDb();
    return fn(state, resDb);
  } finally {
    try { state?.close(); } catch {}
    try { resDb?.close(); } catch {}
  }
}

// "am i up to date? is anything behind?" — the on-demand freshness read, the
// pull side of the watchdog that pushes alerts. Answered from timestamps only
// (no row content, no model), so it is instant and cannot leak a message. Opens
// state.db read-only for the run_log signal; a miss or error returns null and
// the ask route falls through unharmed.
function trySyncStatus(db, question) {
  if (!detectSyncStatus(question)) return null;
  let state = null;
  try {
    const statePath = join(homedir(), '.hazlie', 'connectors', 'state.db');
    state = existsSync(statePath) ? new DatabaseSync(`file:${statePath}?mode=ro`, { readOnly: true }) : null;
    return answerSyncStatus(db, state, {});
  } catch {
    return null;
  } finally {
    try {
      state?.close();
    } catch {}
  }
}

async function handleVaultAsk(db, req, res, cors, policy) {
  if (!hasJsonMediaType(req)) {
    send(res, 415, { error: 'content-type must be application/json' }, cors);
    return;
  }
  const body = await readJson(req);
  assertClosedFields(body, VAULT_ASK_FIELDS);
  const utterance = body.utterance;
  if (typeof utterance !== 'string' || utterance.trim().length === 0) {
    throw badRequest('"utterance" must be a non-empty string');
  }
  if (utterance.length > MAX_UTTERANCE) {
    throw badRequest(`"utterance" must be ${MAX_UTTERANCE} characters or fewer`);
  }

  const question = utterance.trim();

  // Person-search (memory/people/search.mjs): "who are investors I talked to",
  // "who should I reconnect with". Answered from the people GRAPH by code, not
  // the claim/episodic path — the ranker is deterministic and the evidence
  // lines are already human-readable, so no model is called and nobody can be
  // hallucinated onto the list. Tried FIRST because its intent is narrow (a
  // need word plus a people word); a miss returns null and falls straight
  // through to the normal answer path below.
  // Sync-status ("am i up to date?", "is anything behind?"): the freshest,
  // narrowest intent, so it is tried before person-search. Timestamps only,
  // computed by code — the same policy the watchdog alerts on, answered on
  // demand. A non-match returns null and falls straight through.
  const syncStatus = trySyncStatus(db, question);
  if (syncStatus !== null) {
    send(res, 200, { text: syncStatus.text, sources: syncStatus.sources, usedRows: syncStatus.count }, cors);
    return;
  }

  const person = tryPersonSearch(db, question);
  if (person !== null) {
    send(res, 200, { text: person.text, sources: person.sources, usedRows: person.count }, cors);
    return;
  }

  const recalled = recallClaims(db, { match: ftsQuery(question), limit: 12 });

  // The episodic shelf (memory/episodic.mjs): for lookup-shaped questions,
  // code selects raw rows from the owner's own stores and computes the
  // numbers, and the composer reads records alongside claims. Null when the
  // question has no episodic topic — the claim path alone, exactly as before.
  const episodic = episodicContext(db, question);
  const episodicLines = episodic?.lines ?? [];

  // Abstention is decided HERE, before a model exists in the picture. Asking
  // one to say "I don't know" is strictly worse than saying it ourselves, and
  // it spends a model call to do it. With the episodic shelf the condition is
  // now: nothing accepted AND no records either.
  if (recalled.abstain && episodicLines.length === 0) {
    send(res, 200, { text: ABSTAIN, sources: [], usedRows: 0 }, cors);
    return;
  }

  // One numbered sequence: claims first (human-approved, the stronger
  // evidence), then records. Both helpers emit their own [n] prefixes, so the
  // combined list is renumbered once from bare lines. The episodic prompt
  // governs whenever any record is present — it is the one that explains both
  // kinds of line.
  const bare = (l) => l.replace(/^\[\d+\] /u, '');
  const claimLines = recalled.abstain ? [] : groundingLines(recalled.claims);
  const allLines =
    episodicLines.length > 0
      ? [...claimLines, ...episodicLines].map((l, i) => `[${i + 1}] ${bare(l)}`)
      : claimLines;
  const systemPrompt = episodicLines.length > 0 ? readEpisodicPrompt() : readAnswerPrompt();

  // The widget's Cancel is a socket teardown, so client disconnect has to
  // become an abort on the llama call (VOICE-PLAN 3.6). Without this the model
  // keeps generating into a socket nobody is reading, and the next question
  // queues behind a dead one on a single-slot server.
  const controller = new AbortController();
  // Listen on `res`, not `req`: readJson() above consumed the request stream,
  // so req's 'close' has already fired and a listener on it never runs. The
  // response stream is what closes on socket teardown (proxyLlama does the
  // same); writableEnded distinguishes a teardown from an answer we finished.
  const onClose = () => {
    if (!res.writableEnded) controller.abort();
  };
  res.once('close', onClose);
  try {
    const llamaRes = await fetch(`${policy.llama.baseUrl}/v1/chat/completions`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        // apiKey is a GETTER, not a string — it re-reads the file so a rotated
        // key takes effect without a restart (see start()). Interpolating it
        // directly sends the function's source as the bearer token and
        // llama-server answers 401, which is exactly the bug this line had.
        Authorization: `Bearer ${policy.llama.apiKey()}`,
      },
      body: JSON.stringify({
        messages: [
          { role: 'system', content: systemPrompt },
          { role: 'user', content: buildAnswerPrompt({ lines: allLines, question }) },
        ],
        temperature: 0,
        max_tokens: 300,
        stream: false,
      }),
      signal: controller.signal,
    });
    if (!llamaRes.ok) {
      // Unread, the error body pins this keep-alive connection to the
      // single-slot llama-server until GC finalizes the stream — the same
      // failure proxyLlama's cancel() exists for.
      await llamaRes.body?.cancel().catch(() => {});
      send(res, 502, { error: `llama-server returned ${llamaRes.status}` }, cors);
      return;
    }
    const parsed = await llamaRes.json();
    const text = tidyReply(parsed?.choices?.[0]?.message?.content ?? null);
    // A model that returned nothing usable is not a reason to invent one.
    if (text === null) {
      send(res, 200, { text: ABSTAIN, sources: [], usedRows: 0 }, cors);
      return;
    }
    // Source NAMES only, unioned across both shelves — the row-object rule
    // is unchanged, and the widget contract still gets labels, not rows.
    const claimSources = recalled.abstain ? [] : sourceLabels(recalled.claims);
    const sources = [...new Set([...claimSources, ...(episodic?.sources ?? [])])].sort();
    send(
      res,
      200,
      {
        text,
        sources,
        usedRows: (recalled.abstain ? 0 : recalled.claims.length) + (episodic?.rows.length ?? 0),
      },
      cors
    );
  } catch (error) {
    // The client hung up. There is nobody to answer and nothing to log beyond
    // the fact of it; writing to a destroyed socket would throw over the top of
    // the real reason.
    if (controller.signal.aborted) return;
    throw error;
  } finally {
    res.off('close', onClose);
  }
}

function handle(db, req, res, cors, url, policy) {
  // Deliberately the one unauthenticated route: it is the liveness probe for a
  // process that is meant to run for months, and a probe that needs a
  // credential is a probe nobody runs. It answers a bare {ok:true} -- the row
  // count moved to /stats, because `rows` is a monotone counter over a
  // household audio corpus, and serving it to anyone who can reach the port
  // reports when the house is talking without disclosing a single word.
  //
  // THIS BODY IS A WIRE CONTRACT -- do not add a field to it. Three consumers
  // compare it for EXACT equality, and one of them ships: Bridge.swift's
  // checkHermesIdentity string-compares `{"ok":true}` inside the notarized
  // widget, so any extra key makes every already-installed copy fail identity
  // and refuse to ask. ops/setup-connectors.sh:317 and ui/test/hermes.test.mjs
  // compare exactly too. Adding a `service` marker would be a better identity
  // check than a body this guessable -- but it is a coordinated release, not an
  // edit here.
  if (req.method === 'GET' && url.pathname === '/health') {
    send(res, 200, { ok: true }, cors);
    return;
  }

  // Everything below this line requires a caller Hermes recognizes. The check
  // sits here rather than in the request handler above it for two reasons that
  // are easy to break by "tidying" it earlier: OPTIONS is answered before this,
  // because preflights never carry Authorization and gating them breaks every
  // real browser; and the URL parse happens before this, so a malformed Host
  // still gets its 400 instead of a 401 that would retire the crash guard
  // keeping this process alive.
  const channel = authorize(req, policy);
  if (!channel) {
    send(res, 401, { error: 'unauthorized' }, cors);
    return;
  }

  if (req.method === 'GET' && url.pathname === '/stats') {
    const { n } = db.prepare('SELECT count(*) AS n FROM context').get();
    send(res, 200, { rows: Number(n), memory: memoryProgress(db) }, cors);
    return;
  }

  const gone = GONE.get(url.pathname);
  if (gone) {
    send(res, 410, { error: gone }, cors);
    return;
  }

  // Everything under /admin/ is lifecycle territory: dispatched as a prefix so
  // that an unknown admin path still meets the bearer-only gate before its 404
  // — a browser probing /admin/anything learns "not your channel", not a route
  // map.
  if (url.pathname.startsWith('/admin/')) {
    return handleAdmin(db, req, res, cors, url, channel);
  }

  if (req.method === 'POST' && url.pathname === '/ingest') {
    // Authorization gates who may call; this gates what a permitted caller may
    // send. Match the media-type essence exactly: substring matching would
    // accept the CORS-safelisted `text/plain; x=application/json`, which is the
    // shape a page can POST with no preflight.
    if (!hasJsonMediaType(req)) {
      send(res, 415, { error: 'content-type must be application/json' }, cors);
      return;
    }
    return readJson(req).then((body) => {
      // insertRows returns exactly the response contract: how many rows were
      // new, how many replaced an entity in place, and how many were
      // redeliveries the canonical hash proved identical.
      send(res, 200, insertRows(db, body), cors);
    });
  }

  // The lane is the path. Not a header and not a body field: a header would
  // have to be added to Access-Control-Allow-Headers, and forgetting that
  // breaks every preflight and surfaces inside the client as "Hermes is down";
  // a body field would be a default waiting to be inferred. A path cannot be
  // omitted, and a garbled one 404s instead of quietly picking a lane.
  //
  // There is deliberately no unlaned alias. `/v1/chat/completions` is 410, not
  // a redirect to local -- an alias IS the unlaned default this exists to
  // remove.
  if (req.method === 'POST' && url.pathname === '/vault/ask') {
    return handleVaultAsk(db, req, res, cors, policy);
  }

  if (req.method === 'POST' && url.pathname === '/lane/local/v1/chat/completions') {
    if (!hasJsonMediaType(req)) {
      send(res, 415, { error: 'content-type must be application/json' }, cors);
      return;
    }
    return proxyLlama(req, res, cors, policy.llama);
  }

  // Refuses loudly rather than falling back to local. A silent downgrade would
  // make the lane gate look like it works when it does not, and the first
  // person to wire an address signal without a cloud client needs to find out
  // on the first addressed utterance -- not from a metric six weeks later.
  if (req.method === 'POST' && url.pathname === '/lane/cloud/v1/chat/completions') {
    send(res, 501, { error: 'the cloud lane is not built' }, cors);
    return;
  }

  // People / Phase 1 — the "initialize search" backend and its identity-review
  // queue. Bearer-only, like /admin: these read the whole corpus into a people
  // map and WRITE the owner's merge decisions, neither of which is a browser
  // capability. The Origin channel is authenticated but not entitled here, so
  // 403 (not 401), matching handleAdmin's reasoning.
  if (url.pathname === '/people/init' || url.pathname === '/people/review' || url.pathname === '/people/decide' || url.pathname === '/people/map' || url.pathname === '/people/year' || url.pathname === '/people/summary') {
    if (channel !== 'bearer') {
      send(res, 403, { error: 'people routes are bearer-only: call with the token from ~/.hazlie/secrets/hermes-token.txt and no Origin header.' }, cors);
      return;
    }
    return handlePeople(db, req, res, cors, url, policy);
  }

  send(res, 404, { error: `no route for ${req.method} ${url.pathname}` }, cors);
}

// Closed field sets for the /people POST bodies — the same discipline as
// every other write route here: a typo'd key ({day: 30}) must 400, not
// silently build the all-time map.
const PEOPLE_INIT_FIELDS = Object.freeze(['days']);
const PEOPLE_DECIDE_FIELDS = Object.freeze(['verdict', 'a', 'b']);
const PEOPLE_SUMMARY_FIELDS = Object.freeze(['key', 'year']);

// Phase 1 routes. init and review both build the people map and return the
// pairs still needing the owner's eyes; decide records one call. Split out so
// handle() stays a flat dispatch table.
async function handlePeople(db, req, res, cors, url, policy) {
  const owner = loadOwner();

  // Timeframe in days back (0 = all time), from the popup's selector. Clamped to
  // a decade so a fat-fingered value can't ask for an epoch before the corpus.
  const parseDays = (raw) => {
    if (raw === null || raw === undefined || raw === '') return 0;
    const n = Number(raw);
    if (!Number.isInteger(n) || n < 0 || n > 3650) throw badRequest('"days" must be an integer 0..3650 (0 = all time)');
    return n;
  };
  const parseLimit = (raw) => {
    if (raw === null || raw === undefined || raw === '') return 40;
    const n = Number(raw);
    if (!Number.isInteger(n) || n < 1 || n > 100) throw badRequest('"limit" must be an integer 1..100');
    return n;
  };

  if (req.method === 'POST' && url.pathname === '/people/init') {
    if (!hasJsonMediaType(req)) { send(res, 415, { error: 'content-type must be application/json' }, cors); return; }
    const body = await readJson(req);
    assertClosedFields(body, PEOPLE_INIT_FIELDS);
    const days = parseDays(body?.days);
    const out = withPeopleDbs(db, (state, resDb) => peopleReview(db, state, resDb, { days, owner }));
    send(res, 200, out, cors);
    return;
  }

  if (req.method === 'GET' && url.pathname === '/people/review') {
    const days = parseDays(url.searchParams.get('days'));
    const limit = parseLimit(url.searchParams.get('limit'));
    const out = withPeopleDbs(db, (state, resDb) => peopleReview(db, state, resDb, { days, owner, limit }));
    send(res, 200, out, cors);
    return;
  }

  // The constellation: every person as a star, clustered and lit. Folds in the
  // owner's confirmed merges (aliases) so a merged person is one star.
  if (req.method === 'GET' && url.pathname === '/people/map') {
    const days = parseDays(url.searchParams.get('days'));
    const sinceTs = days > 0 ? Date.now() - days * 86_400_000 : null;
    const out = withPeopleDbs(db, (state, resDb) => {
      const { aliases } = resolutionState(resDb);
      return buildMap(db, state, { owner, sinceTs, aliases });
    });
    send(res, 200, out, cors);
    return;
  }

  // The timeline view: one year of people by that year's engagement, with
  // the year's topics. Same auth posture as map.
  if (req.method === 'GET' && url.pathname === '/people/year') {
    const raw = url.searchParams.get('year');
    const thisYear = new Date().getFullYear();
    const year = raw === null || raw === '' ? thisYear : Number(raw);
    if (!Number.isInteger(year) || year < 1990 || year > thisYear + 1) {
      throw badRequest(`"year" must be an integer 1990..${thisYear + 1}`);
    }
    const out = withPeopleDbs(db, (state, resDb) => {
      const { aliases } = resolutionState(resDb);
      return buildYear(db, state, { year, owner, aliases });
    });
    send(res, 200, out, cors);
    return;
  }

  // The year summary: model-written, LOCAL llama only, generated on demand
  // for one person and cached against the corpus stamp (people/summary.mjs
  // carries the boundary reasoning). POST because the person key is data,
  // not a path.
  if (req.method === 'POST' && url.pathname === '/people/summary') {
    if (!hasJsonMediaType(req)) { send(res, 415, { error: 'content-type must be application/json' }, cors); return; }
    const body = await readJson(req);
    assertClosedFields(body, PEOPLE_SUMMARY_FIELDS);
    if (typeof body?.key !== 'string' || body.key.length === 0 || body.key.length > 300) {
      throw badRequest('"key" must be a person key');
    }
    const thisYear = new Date().getFullYear();
    const year = Number(body?.year);
    if (!Number.isInteger(year) || year < 1990 || year > thisYear + 1) {
      throw badRequest(`"year" must be an integer 1990..${thisYear + 1}`);
    }
    // withPeopleDbs closes its handles in finally — safe here because every
    // database read in summarizeYear happens in its SYNCHRONOUS prologue
    // (graph + row gather); only the llama fetch is awaited, and it touches
    // no handle. If summarizeYear ever grows an await before its reads, this
    // call site must change with it.
    const out = await withPeopleDbs(db, (state, resDb) => {
      const { aliases } = resolutionState(resDb);
      return summarizeYear(db, state, { personKey: body.key, year, owner, aliases, llama: policy.llama });
    });
    send(res, 200, out, cors);
    return;
  }

  if (req.method === 'POST' && url.pathname === '/people/decide') {
    if (!hasJsonMediaType(req)) { send(res, 415, { error: 'content-type must be application/json' }, cors); return; }
    const body = await readJson(req);
    assertClosedFields(body, PEOPLE_DECIDE_FIELDS);
    const verdict = body?.verdict;
    if (verdict !== 'same' && verdict !== 'different' && verdict !== 'skip') {
      throw badRequest('"verdict" must be one of same, different, skip');
    }
    if (typeof body?.a !== 'string' || typeof body?.b !== 'string' || !body.a || !body.b || body.a === body.b) {
      throw badRequest('"a" and "b" must be two distinct person keys');
    }
    const out = withPeopleDbs(db, (_state, resDb) => peopleDecide(resDb, { a: body.a, b: body.b, verdict }));
    send(res, 200, out, cors);
    return;
  }

  send(res, 404, { error: `no route for ${req.method} ${url.pathname}` }, cors);
}

// Tests start this on an ephemeral port with a throwaway DB; the CLI entry at
// the bottom starts it with the real defaults. Returns once listening.
//
// `async` so that a missing secret file rejects rather than throwing
// synchronously. It used to throw: the key validation below runs before the
// listen promise is constructed, so `start().then(ok, fail)` at the bottom of
// this file never reached `fail` and a fresh machine got a raw stack trace
// instead of the sentence naming the fix. Two secrets to provision now, so the
// path is twice as easy to land on.
export async function start({
  // 51789, not 8787: the canonical port moved on 2026-08-20 (MEMORY-PLAN Day 0)
  // because an unrelated dev server holds 8787 on the owner's Mac and answers
  // 200 there, which made every defaulted caller reach a stranger. One number,
  // set here and echoed by DEFAULT_HERMES_BASE_URL in connectors/lib/
  // ingestClient.mjs and the probe in ops/setup-connectors.sh — change all
  // three together or not at all.
  port = Number(process.env.HERMES_PORT ?? 51789),
  dbPath,
  allowedOrigins = process.env.HERMES_ALLOWED_ORIGINS,
  llamaBaseUrl = process.env.HERMES_LLAMA_URL ?? DEFAULT_LLAMA_BASE_URL,
  llamaApiKey,
  llamaApiKeyFile = process.env.HERMES_LLAMA_API_KEY_FILE ?? DEFAULT_LLAMA_API_KEY_PATH,
  bearerToken: fixedBearerToken,
  bearerTokenFile = process.env.HERMES_TOKEN_FILE ?? DEFAULT_HERMES_TOKEN_PATH,
} = {}) {
  const allowedOriginSet = parseAllowedOrigins(allowedOrigins);
  let apiKey;
  if (llamaApiKey === undefined) {
    // Fail startup early, then re-read per request so setup can rotate the key
    // without leaving a long-running Hermes process stuck on the old value.
    readLlamaApiKey(llamaApiKeyFile);
    apiKey = () => readLlamaApiKey(llamaApiKeyFile);
  } else {
    const fixedApiKey = validateHexKey(llamaApiKey, 'llama API key');
    apiKey = () => fixedApiKey;
  }
  // Same discipline as the llama key: validate once so a missing token is a
  // startup failure with a fix in the message, then re-read per request so
  // rotation does not need a restart. Only the bearer channel pays that read --
  // browser requests are authorized by Origin and never touch the file, so the
  // voice loop's per-turn path does no filesystem work here.
  let bearerToken;
  if (fixedBearerToken === undefined) {
    readHermesToken(bearerTokenFile);
    bearerToken = () => readHermesToken(bearerTokenFile);
  } else {
    const token = validateHexKey(fixedBearerToken, 'Hermes bearer token');
    bearerToken = () => token;
  }
  const llama = {
    baseUrl: canonicalLoopbackBase(llamaBaseUrl),
    apiKey,
  };
  const db = openDb(dbPath ?? process.env.HERMES_DB ?? DEFAULT_DB_PATH);

  const server = createServer(async (req, res) => {
    const cors = corsHeaders(req, allowedOriginSet);

    if (req.method === 'OPTIONS') {
      res.writeHead(204, { ...PRIVATE_RESPONSE_HEADERS, ...cors });
      res.end();
      return;
    }

    // Host is attacker-controlled bytes and a space in it is a legal header
    // value that WHATWG URL rejects; an unguarded parse here is an unhandled
    // rejection that kills the household's 24/7 memory process.
    let url;
    try {
      url = new URL(req.url, `http://${req.headers.host ?? 'localhost'}`);
    } catch {
      send(res, 400, { error: 'unparseable request URL' }, cors);
      return;
    }

    try {
      await handle(db, req, res, cors, url, {
        allowedOrigins: allowedOriginSet,
        bearerToken,
        llama,
      });
    } catch (e) {
      send(res, e.status ?? 500, { error: e.message ?? String(e) }, cors);
    }
  });

  return new Promise((resolve, reject) => {
    server.once('error', reject);
    server.listen(port, '127.0.0.1', () => {
      resolve({
        server,
        db,
        port: server.address().port,
        close: () =>
          new Promise((done, fail) => {
            server.close((err) => {
              db.close();
              err ? fail(err) : done();
            });
          }),
      });
    });
  });
}

const isMain =
  process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;

if (isMain) {
  start().then(
    ({ port, db }) => {
      const { n } = db.prepare('SELECT count(*) AS n FROM context').get();
      console.log(
        `hermes listening on http://127.0.0.1:${port} (context rows: ${n})`
      );
    },
    (e) => {
      console.error(`hermes failed to start: ${e.message ?? e}`);
      process.exit(1);
    }
  );
}
