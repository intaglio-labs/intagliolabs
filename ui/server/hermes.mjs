// EMPTY BY DEFAULT since 2026-08-23, and the reason is the whole point of the
// browser channel having existed at all.
//
// This used to default to Expo's two web-dev origins, http://localhost:8081 and
// http://127.0.0.1:8081. The justification, written above authorize(), was that
// the page holds no secret and inlining one through EXPO_PUBLIC_* would ship it
// in the bundle -- so a present, allowlisted Origin had to stand in for a token.
//
// That justification was a fact about the Expo app, and the Expo app is gone:
// AssetScheme.swift replaced it with the hazlie-asset:// scheme, and every
// consumer that still exists reaches hermes on the bearer channel with NO Origin
// header -- Bridge.swift ("No Origin header is ever set"), connect/lib/bridge.mjs,
// connect/lib/memory.mjs, connectors' ingestClient, and the ui/scripts CLIs.
// Nothing in this product sends an Origin to hermes any more.
//
// So the token-free channel had no remaining consumer, while still costing the
// residual gap authorize() documents: a same-machine process running as another
// uid could send `Origin: http://localhost:8081` and be authorized without
// knowing the token. Paying for a gap to serve nobody is strictly worse than not
// having the channel, and closing it needs no new mechanism -- parseAllowedOrigins
// already treats an empty list as "no browser access, CLI unaffected".
//
// A dev surface that genuinely needs the browser channel sets
// HERMES_ALLOWED_ORIGINS explicitly. That is the difference this change is really
// making: the trust is now declared by whoever wants it, not inherited by
// whatever happens to hold port 8081.
export const DEFAULT_ALLOWED_ORIGINS = Object.freeze([]);

function canonicalOrigin(raw) {
  const value = String(raw).trim();
  if (!value) return null;
  let url;
  try {
    url = new URL(value);
  } catch {
    throw new Error(`invalid HERMES_ALLOWED_ORIGINS entry: ${JSON.stringify(value)}`);
  }
  if (
    (url.protocol !== 'http:' && url.protocol !== 'https:') ||
    url.username ||
    url.password ||
    url.pathname !== '/' ||
    url.search ||
    url.hash
  ) {
    throw new Error(
      `HERMES_ALLOWED_ORIGINS entries must be HTTP(S) origins: ${JSON.stringify(value)}`
    );
  }
  return url.origin;
}

// HERMES_ALLOWED_ORIGINS is a comma-separated list of exact origins. Unset now
// means NO browser origin is trusted (see DEFAULT_ALLOWED_ORIGINS); an explicitly
// empty value means the same thing. Either way the bearer channel -- no Origin
// plus the 0600 token -- is unaffected, which is how every real caller arrives.
export function parseAllowedOrigins(raw) {
  const entries =
    raw === undefined
      ? DEFAULT_ALLOWED_ORIGINS
      : typeof raw === 'string'
        ? raw.split(',')
        : Array.from(raw);
  const origins = new Set();
  for (const entry of entries) {
    const origin = canonicalOrigin(entry);
    if (origin) origins.add(origin);
  }
  return origins;
}

// Exported because every base URL this package builds from the environment has
// to pass it, not just HERMES_LLAMA_URL: scripts/distill-once.mjs carries whole
// corpus rows and the llama key to whatever HAZLIE_LLAMA_URL names, and
// scripts/seed-context.mjs carries the hermes bearer. While this was private,
// each of those read its env var raw. `label` exists so the thrown message
// names the variable the operator actually set.
export function canonicalLoopbackBase(raw, label = 'HERMES_LLAMA_URL') {
  let url;
  try {
    url = new URL(String(raw));
  } catch {
    throw new Error(`${label} must be an HTTP loopback origin`);
  }
  const loopback =
    url.hostname === '127.0.0.1' ||
    url.hostname === 'localhost' ||
    url.hostname === '[::1]' ||
    url.hostname === '::1';
  if (
    url.protocol !== 'http:' ||
    !loopback ||
    url.username ||
    url.password ||
    url.pathname !== '/' ||
    url.search ||
    url.hash
  ) {
    throw new Error(`${label} must be an HTTP loopback origin`);
  }
  return url.origin;
}

function validateHexKey(value, label) {
  const key = String(value ?? '').trim();
  if (!/^[0-9a-f]{64}$/.test(key)) {
    throw new Error(`${label} must be one generated 256-bit hex key`);
  }
  return key;
}

// Both of Hermes' secrets are 256-bit hex in an owner-only file, so they get
// one loader rather than two that drift. Every check here is load-bearing:
// lstat (not stat) so a symlink is rejected instead of followed to a file whose
// mode says nothing about the link; a regular-file test; owner-only mode;
// owner-is-us; and the parent directory's mode, which the llama key loader
// never checked -- an 0600 file inside a group-writable directory is not
// owner-only, because whoever can write the directory can replace the file.
// openDb has enforced exactly this on the database directory since it was
// written; the secrets directory never had it.
function readSecretFile(filePath, { label, setupHint = 'run ops/setup-llm.sh' }) {
  let info;
  try {
    info = lstatSync(filePath);
  } catch (error) {
    if (error?.code === 'ENOENT') {
      throw new Error(`${label} file is missing; ${setupHint}`);
    }
    throw error;
  }
  if (!info.isFile()) {
    throw new Error(`${label} path must be a regular, non-symlink file`);
  }
  if ((info.mode & 0o077) !== 0) {
    throw new Error(`${label} file must not be accessible by group or other users`);
  }
  if (typeof process.getuid === 'function' && info.uid !== process.getuid()) {
    throw new Error(`${label} file must be owned by the Hermes user`);
  }
  const secretDir = dirname(filePath);
  const secretDirMode = statSync(secretDir).mode & 0o777;
  if (secretDirMode !== 0o700) {
    throw new Error(
      `${label} directory must have mode 0700: ${secretDir} is ${secretDirMode.toString(8)}`
    );
  }
  return validateHexKey(readFileSync(filePath, 'utf8'), label);
}

export function readLlamaApiKey(filePath = DEFAULT_LLAMA_API_KEY_PATH) {
  return readSecretFile(filePath, { label: 'llama API key' });
}

export function readHermesToken(filePath = DEFAULT_HERMES_TOKEN_PATH) {
  return readSecretFile(filePath, { label: 'Hermes bearer token' });
}

// ui/.env.local is the one place local config lives for this project. Node
// does not load it on its own, and adding dotenv for a 15-line parse is not
// worth a dependency. Values already present in the environment win, so
// `HERMES_PORT=... npm run hermes` still works for one-off overrides.
function loadEnvLocal() {
  let text;
  try {
    text = readFileSync(join(here, '..', '.env.local'), 'utf8');
  } catch {
    return; // no file is fine; nothing here is required to boot
  }
  for (const line of text.split('\n')) {
    if (line.trim().startsWith('#')) continue;
    const m = /^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$/.exec(line);
    if (m && !(m[1] in process.env)) process.env[m[1]] = m[2];
  }
}
