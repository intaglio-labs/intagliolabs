// POST /vault/ask -- the desktop widget's question surface.
//
// NOT under /admin/, and not bearer-only: the widget is a native client that
// sends no Origin header, which selects the bearer channel, but an allowlisted
// page asking a question is the same trust level as /lane/local. What it is NOT
// is public -- authorize() still has to return a channel.
//
// BUFFERED JSON, NOT SSE. Deliberately: the answer is two sentences composed
// from at most 25 short claims, so streaming would add a protocol for no
// perceptible latency win and give the boundary a second shape to defend.
//
// The response is exactly {text, sources, usedRows}. `sources` is source NAMES
// only. A row object there would put the owner's verbatim words into a client
// that is outside the corpus boundary, which is the one thing this whole layer
// exists to prevent.
const VAULT_ASK_FIELDS = Object.freeze(['utterance']);
// VOICE-PLAN names 2000. Refused rather than truncated: a silently shortened
// question gets answered as if it were the whole question, and the asker never
// learns which half was dropped.
const MAX_UTTERANCE = 2000;

// The spine (contacts) lives in the connectors' state.db, a different file
// from the context store. Opened read-only, per call, only when a person
// search actually fires — the graph build is ~1s and not worth holding a
// handle for questions that are not person-searches. Returns null on any
// error or a non-match, so the ask route falls through unharmed.
function tryPersonSearch(db, question) {
  try {
    return withPeopleDbs(db, (state, resDb) => {
      const { aliases } = resolutionState(resDb);
      return answerPersonSearch(db, state, question, { owner: loadOwner(), aliases });
    });
  } catch {
    return null;
  }
}

// Unfamiliar people questions use the local model only as a constrained plan
// compiler and evidence judge. The state/resolution handles are held only for
// the synchronous projection + retrieval phase; no connector database stays
// open while the single-slot model is generating.
async function tryGeneralPeopleSearch(
  db,
  question,
  llama,
  { signal = null, cache = null, onStage = null } = {}
) {
  const now = Date.now();
  const cacheGeneration = cache?.generation?.();
  const owner = loadOwner();
  const recalled = recallClaims(db, { match: ftsQuery(question), limit: 6 });
  const ownerMemories = recalled.matched > 0
    ? recalled.claims.map((claim) => claim.text).filter(Boolean)
    : [];
  const plan = await planGeneralPeopleQuestion(question, {
    llama, signal, owner, ownerMemories, cache, onStage, now,
  });
  if (plan === null || plan.kind === 'not_people_search') return null;
  let prepared;
  let answerCacheInput = null;
  let cachedAnswer = null;
  try {
    prepared = withPeopleDbs(db, (state, resDb) => {
      const { aliases } = resolutionState(resDb);
      if (cache) {
        answerCacheInput = generalPeopleAnswerCacheInput(db, state, question, plan, {
          owner, aliases, now, limit: 10, model: llama.model ?? llama.baseUrl,
        });
        cachedAnswer = cache.get('answer', answerCacheInput);
        try {
          onStage?.({ stage: 'answer', event: cachedAnswer === null ? 'cache_miss' : 'cache_hit' });
        } catch {}
        if (cachedAnswer !== null) return null;
      }
      return prepareGeneralPeopleEvidence(db, state, plan, {
        owner, aliases, now,
      });
    });
  } catch {
    return {
      text: `I couldn't refresh the local people evidence index just now. Your source data is unchanged; try again in a moment.`,
      sources: [], count: 0,
    };
  }
  if (cachedAnswer !== null) return cachedAnswer;
  const matches = await evaluateGeneralPeopleEvidence(question, prepared, {
    llama, signal, limit: 10, cache, onStage,
  });
  const result = formatGeneralPeopleResult(matches, prepared);
  if (answerCacheInput) cache.put('answer', answerCacheInput, result, cacheGeneration);
  return result;
}

function preferDeterministicRelationshipSearch(question) {
  if (detectIntro(question) !== null) return true;
  const intent = detectPersonSearch(question);
  return intent?.kind === 'reconnect';
}

// The People-popup "initialize search" backend. Opens the spine read-only (like
// tryPersonSearch) and the owner's decisions store read-write, runs `fn`, and
// always closes both — even on throw — so a build never leaks a handle. The
// context db (the main store) is the caller's already-open handle. Errors
// propagate: unlike the ask-path helpers, these are explicit routes the widget
// invoked, so a failure should surface as a 500, not a silent null.
// Build the people core once, at boot, on the same handles a request would use.
// Exported shape matches yearCore's so the caller can log a count without
// reaching into it.
// ON REQUEST. The owner asked for "recomputed... every day or on request", and
// this is the second half: a blocking rebuild the page can ask for by hand when
// it does not want to wait for the background one.
//
// Blocking on purpose. Everything else in this file goes out of its way NOT to
// block -- but somebody who pressed refresh is asking to wait, and returning
// instantly with the same stale numbers would read as the button doing nothing.
function rebuildPeopleCore(db) {
  try {
    withPeopleDbs(db, (state, resDb) => {
      const { aliases } = resolutionState(resDb);
      return yearCore(db, state, { now: Date.now(), owner: loadOwner(), aliases, blocking: true });
    });
  } catch {
    // A failed rebuild leaves the previous core in place: stale, not wrong.
  }
}

function warmPeopleCore(db) {
  return withPeopleDbs(db, (state, resDb) => {
    const { aliases } = resolutionState(resDb);
    return yearCore(db, state, { now: Date.now(), owner: loadOwner(), aliases, blocking: true });
  });
}

// Coalesce connector batches into one background projection refresh after the
// ingest stream goes quiet. Rebuilding after every 200-row backfill batch would
// be worse than rebuilding on search; waiting for a quiet edge preserves fresh
// prepared tables without turning ingestion into repeated full graph work.
const peopleProjectionTimers = new WeakMap();
function schedulePeopleProjectionRefresh(db) {
  const pending = peopleProjectionTimers.get(db);
  if (pending) clearTimeout(pending);
  const timer = setTimeout(() => {
    peopleProjectionTimers.delete(db);
    try {
      withPeopleDbs(db, (state, resDb) => {
        const { aliases } = resolutionState(resDb);
        materializedPeopleGraph(db, state, { now: Date.now(), owner: loadOwner(), aliases });
      });
    } catch {
      // It remains stale and the next search uses the raw fallback or retries.
    }
  }, 30_000);
  timer.unref?.();
  peopleProjectionTimers.set(db, timer);
}

// The rebuild that was missing entirely: clearPeopleProjection() (a privacy
// purge, or /admin/people/clear) leaves `people` empty and
// projected_revision at -1 until something calls materializedPeopleGraph --
// which previously only happened when the People page or search ran. Every
// server-side reader in between (including a fresh boot, when the state was
// already -1/0 from a purge that ran before the last restart) saw an empty
// table. This is the eager trigger for both of those moments.
//
// Holder-per-process, same pattern as relationshipState: rebuilding/
// lastRebuildError live on policy.peopleProjectionHolder (or policy itself,
// for callers -- tests -- that pass a bare holder), not on the module, so
// concurrent hermes instances in one process (tests) do not share state.
// setImmediate, not a new timer/scheduler: this fires once, after the
// request that triggered it (server.listen, or the clear/retain/purge/
// delete-entities route) has already returned.
//
// policy.peopleProjectionAutoRebuild (default true; a start() test seam like
// relationshipMatcher/relationshipCap) exists because "returns first" is not
// "runs so much later that a synchronous DB check after the response
// resolves stays clean" -- a bare setImmediate can and does land inside the
// same tick a fast-running test's `await fetch(...)` resumes in. Several
// existing lifecycle tests assert the projection is empty in the instant
// after a clear/purge, which this feature makes racy by design; they opt out
// with this flag rather than the production default changing for them.
function schedulePeopleRebuild(db, policy, reason) {
  if (policy.peopleProjectionAutoRebuild === false) return;
  const holder = policy.peopleProjectionHolder ?? policy;
  if (!holder.__peopleProjection) {
    holder.__peopleProjection = { rebuilding: false, lastRebuildError: null };
  }
  const state = holder.__peopleProjection;
  if (state.rebuilding) return;
  state.rebuilding = true;
  setImmediate(() => {
    try {
      withPeopleDbs(db, (peopleDb, resDb) => {
        const { aliases } = resolutionState(resDb);
        materializedPeopleGraph(db, peopleDb, { now: Date.now(), owner: loadOwner(), aliases, force: false });
      });
      state.lastRebuildError = null;
    } catch (e) {
      // Surfaced on /stats' peopleProjection.lastRebuildError rather than
      // thrown: the request that scheduled this already answered, and a
      // failed rebuild leaves the previous (possibly empty) projection in
      // place for the raw-rebuild fallback to cover, same as every other
      // projection failure in this file.
      state.lastRebuildError = String(e?.message ?? e);
      console.error(`people projection rebuild (${reason}) failed:`, e?.stack ?? e);
    } finally {
      state.rebuilding = false;
    }
  });
}

// WAIT FOR THE WRITER; DO NOT GIVE UP AND CALL IT AN ANSWER.
//
// state.db is the connectors' database and it runs journal_mode=DELETE, on
// purpose -- contact names must not survive legibly in a -wal sidecar. So a
// writer excludes readers, and the contacts connector upserts batches into it.
// With SQLite's default busy timeout of ZERO, a read
// landing inside that window fails instantly.
//
// That failure used to be swallowed into an empty contacts spine, and an empty
// spine is not a smaller answer -- it is a different one. Every person known
// only through the address book loses their name and reverts to a raw handle,
// and worse, two handles belonging to one person stop merging, so they split
// into two people with the messages divided between them. Then yearCore
// memoised it. Private testing observed one person's messages split across two
// records exactly this way.
function openStateReadOnly(statePath) {
  const db = new DatabaseSync(`file:${statePath}?mode=ro`, { readOnly: true });
  db.exec('PRAGMA busy_timeout = 5000');
  return db;
}

function withPeopleDbs(db, fn) {
  let state = null;
  let resDb = null;
  try {
    const statePath = join(homedir(), '.hazlie', 'connectors', 'state.db');
    state = existsSync(statePath) ? openStateReadOnly(statePath) : null;
    resDb = openResolutionsDb();
    return fn(state, resDb);
  } finally {
    try { state?.close(); } catch {}
    try { resDb?.close(); } catch {}
  }
}

// "am i up to date? is anything behind?" — the on-demand freshness read, the
// pull side of the watchdog that pushes alerts. Answered from timestamps only
// (no row content, no model), so it is instant and cannot leak a message. Opens
// state.db read-only for the run_log signal; a miss or error returns null and
// the ask route falls through unharmed.
function trySyncStatus(db, question) {
  if (!detectSyncStatus(question)) return null;
  let state = null;
  try {
    const statePath = join(homedir(), '.hazlie', 'connectors', 'state.db');
    state = existsSync(statePath) ? openStateReadOnly(statePath) : null;
    return answerSyncStatus(db, state, {});
  } catch {
    return null;
  } finally {
    try {
      state?.close();
    } catch {}
  }
}

async function handleVaultAsk(db, req, res, cors, policy) {
  if (!hasJsonMediaType(req)) {
    send(res, 415, { error: 'content-type must be application/json' }, cors);
    return;
  }
  const body = await readJson(req);
  assertClosedFields(body, VAULT_ASK_FIELDS);
  const utterance = body.utterance;
  if (typeof utterance !== 'string' || utterance.trim().length === 0) {
    throw badRequest('"utterance" must be a non-empty string');
  }
  if (utterance.length > MAX_UTTERANCE) {
    throw badRequest(`"utterance" must be ${MAX_UTTERANCE} characters or fewer`);
  }

  const question = utterance.trim();

  // Sync-status ("am i up to date?", "is anything behind?") is the freshest,
  // narrowest intent and stays first. Timestamps only, computed by code — the
  // same policy the watchdog alerts on, answered on demand. A non-match falls
  // through to graph relationship operations and then general evidence-based
  // people search.
  const syncStatus = trySyncStatus(db, question);
  if (syncStatus !== null) {
    send(res, 200, { text: syncStatus.text, sources: syncStatus.sources, usedRows: syncStatus.count }, cors);
    return;
  }

  // Warm paths and relationship-health searches are graph operations, not
  // evidence questions, so they keep their purpose-built graph traversal and
  // ranking. Every evidence-based selection question goes through the general
  // planner below; there are no topic-specific shortcuts ahead of it.
  const relationshipSearch = preferDeterministicRelationshipSearch(question);
  if (relationshipSearch) {
    const person = tryPersonSearch(db, question);
    if (person !== null) {
      send(res, 200, { text: person.text, sources: person.sources, usedRows: person.count }, cors);
      return;
    }
  }

  // Evidence-based people questions all reach the same general local planner.
  // The first model call sees the question plus explicit owner-profile facts,
  // code retrieves a bounded candidate set, and the second local call can
  // return only supplied person + evidence ids.
  const peopleController = new AbortController();
  const peopleClosed = () => {
    if (!res.writableEnded) peopleController.abort();
  };
  res.once('close', peopleClosed);
  let generalPerson;
  try {
    generalPerson = await tryGeneralPeopleSearch(db, question, policy.llama, {
      cache: policy.peopleSearchCache,
      signal: AbortSignal.any([
        peopleController.signal,
        AbortSignal.timeout(policy.askTimeoutMs ?? ASK_TIMEOUT_MS),
      ]),
    });
  } catch (error) {
    if (peopleController.signal.aborted) return;
    throw error;
  } finally {
    res.off('close', peopleClosed);
  }
  if (generalPerson !== null) {
    send(res, 200, {
      text: generalPerson.text,
      sources: generalPerson.sources,
      usedRows: generalPerson.count,
    }, cors);
    return;
  }

  // Non-question-shaped legacy need queries (for example, "investors I spoke
  // with") do not activate the general planner's conservative question gate.
  // They retain the existing graph answer as a fallback, after the general
  // path has had first refusal for any normal people question.
  if (!relationshipSearch) {
    const person = tryPersonSearch(db, question);
    if (person !== null) {
      send(res, 200, { text: person.text, sources: person.sources, usedRows: person.count }, cors);
      return;
    }
  }

  const recalled = recallClaims(db, { match: ftsQuery(question), limit: 12 });

  // The episodic shelf (memory/episodic.mjs): for lookup-shaped questions,
  // code selects raw rows from the owner's own stores and computes the
  // numbers, and the composer reads records alongside claims. Null when the
  // question has no episodic topic — the claim path alone, exactly as before.
  const episodic = episodicContext(db, question);
  const episodicLines = episodic?.lines ?? [];

  // Abstention is decided HERE, before a model exists in the picture. Asking
  // one to say "I don't know" is strictly worse than saying it ourselves, and
  // it spends a model call to do it. With the episodic shelf the condition is
  // now: nothing accepted AND no records either.
  if (recalled.abstain && episodicLines.length === 0) {
    send(res, 200, { text: ABSTAIN, sources: [], usedRows: 0 }, cors);
    return;
  }

  // One numbered sequence: claims first (human-approved, the stronger
  // evidence), then records. Both helpers emit their own [n] prefixes, so the
  // combined list is renumbered once from bare lines. The episodic prompt
  // governs whenever any record is present — it is the one that explains both
  // kinds of line.
  const bare = (l) => l.replace(/^\[\d+\] /u, '');
  const claimLines = recalled.abstain ? [] : groundingLines(recalled.claims);
  const allLines =
    episodicLines.length > 0
      ? [...claimLines, ...episodicLines].map((l, i) => `[${i + 1}] ${bare(l)}`)
      : claimLines;
  const systemPrompt = episodicLines.length > 0 ? readEpisodicPrompt() : readAnswerPrompt();

  // The widget's Cancel is a socket teardown, so client disconnect has to
  // become an abort on the llama call (VOICE-PLAN 3.6). Without this the model
  // keeps generating into a socket nobody is reading, and the next question
  // queues behind a dead one on a single-slot server.
  const controller = new AbortController();
  // Listen on `res`, not `req`: readJson() above consumed the request stream,
  // so req's 'close' has already fired and a listener on it never runs. The
  // response stream is what closes on socket teardown (proxyLlama does the
  // same); writableEnded distinguishes a teardown from an answer we finished.
  const onClose = () => {
    if (!res.writableEnded) controller.abort();
  };
  res.once('close', onClose);
  try {
    const llamaRes = await fetch(`${policy.llama.baseUrl}/v1/chat/completions`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        // apiKey is a GETTER, not a string — it re-reads the file so a rotated
        // key takes effect without a restart (see start()). Interpolating it
        // directly sends the function's source as the bearer token and
        // llama-server answers 401, which is exactly the bug this line had.
        Authorization: `Bearer ${policy.llama.apiKey()}`,
      },
      body: JSON.stringify({
        ...(policy.llama.model ? { model: policy.llama.model } : {}),
        messages: [
          { role: 'system', content: systemPrompt },
          { role: 'user', content: buildAnswerPrompt({ lines: allLines, question }) },
        ],
        temperature: 0,
        max_tokens: 300,
        stream: false,
      }),
      // A CEILING, as well as the owner's Cancel. This had only the disconnect
      // signal, so a model that never answered held this request -- and the
      // single-slot server behind it -- open for as long as the socket lived.
      // 110s sits just inside the widget's own 120s (Bridge.swift's
      // timeoutIntervalForRequest), so hermes is the one that answers: a clean
      // status the widget can render rather than a transport error it cannot.
      signal: AbortSignal.any([
        controller.signal,
        AbortSignal.timeout(policy.askTimeoutMs ?? ASK_TIMEOUT_MS),
      ]),
      // A compromised or misconfigured loopback service must not redirect a
      // household prompt (or its Authorization header) onto the network. Every
      // other llama call in the tree says this; this one -- which carries the
      // retrieved context AND the key -- did not.
      redirect: 'error',
    });
    if (!llamaRes.ok) {
      // Unread, the error body pins this keep-alive connection to the
      // single-slot llama-server until GC finalizes the stream — the same
      // failure proxyLlama's cancel() exists for.
      await llamaRes.body?.cancel().catch(() => {});
      send(res, 502, { error: `llama-server returned ${llamaRes.status}` }, cors);
      return;
    }
    const parsed = await llamaRes.json();
    const text = tidyReply(parsed?.choices?.[0]?.message?.content ?? null);
    // A model that returned nothing usable is not a reason to invent one.
    if (text === null) {
      send(res, 200, { text: ABSTAIN, sources: [], usedRows: 0 }, cors);
      return;
    }
    // Source NAMES only, unioned across both shelves — the row-object rule
    // is unchanged, and the widget contract still gets labels, not rows.
    const claimSources = recalled.abstain ? [] : sourceLabels(recalled.claims);
    const sources = [...new Set([...claimSources, ...(episodic?.sources ?? [])])].sort();
    send(
      res,
      200,
      {
        text,
        sources,
        usedRows: (recalled.abstain ? 0 : recalled.claims.length) + (episodic?.rows.length ?? 0),
      },
      cors
    );
  } catch (error) {
    // The client hung up. There is nobody to answer and nothing to log beyond
    // the fact of it; writing to a destroyed socket would throw over the top of
    // the real reason.
    if (controller.signal.aborted) return;
    // "The model is not running" is not an application error, and it is the one
    // failure here the owner can be told something true about. Unshaped, it
    // reached them as "something went wrong on this app's side".
    if (isUnreachable(error)) throw unreachableError();
    // NOR IS "it did not answer in time". The ceiling above aborts the COMBINED
    // signal, so the disconnect controller reads as not-aborted and the guard
    // above misses it -- which sent a 110s wait to the owner as an app bug,
    // arriving before the widget's own 120s would have said anything at all.
    if (isTimeout(error)) throw timeoutError();
    throw error;
  } finally {
    res.off('close', onClose);
  }
}

async function handle(db, req, res, cors, url, policy) {
  // Deliberately the one unauthenticated route: it is the liveness probe for a
  // process that is meant to run for months, and a probe that needs a
  // credential is a probe nobody runs. It answers a bare {ok:true} -- the row
  // count moved to /stats, because `rows` is a monotone counter over a
  // household audio corpus, and serving it to anyone who can reach the port
  // reports when the house is talking without disclosing a single word.
  //
  // THIS BODY IS A WIRE CONTRACT -- do not add a field to it. Three consumers
  // compare it for EXACT equality, and one of them ships: Bridge.swift's
  // checkHermesIdentity string-compares `{"ok":true}` inside the notarized
  // widget, so any extra key makes every already-installed copy fail identity
  // and refuse to ask. ops/setup-connectors.sh:317 and ui/test/hermes.test.mjs
  // compare exactly too. Adding a `service` marker would be a better identity
  // check than a body this guessable -- but it is a coordinated release, not an
  // edit here.
  if (req.method === 'GET' && url.pathname === '/health') {
    send(res, 200, { ok: true }, cors);
    return;
  }

  // Everything below this line requires a caller Hermes recognizes. The check
  // sits here rather than in the request handler above it for two reasons that
  // are easy to break by "tidying" it earlier: OPTIONS is answered before this,
  // because preflights never carry Authorization and gating them breaks every
  // real browser; and the URL parse happens before this, so a malformed Host
  // still gets its 400 instead of a 401 that would retire the crash guard
  // keeping this process alive.
  const channel = authorize(req, policy);
  if (!channel) {
    send(res, 401, { error: 'unauthorized' }, cors);
    return;
  }

  if (req.method === 'GET' && url.pathname === '/stats') {
    const { n } = db.prepare('SELECT count(*) AS n FROM context').get();
    // sweepStatus is a plain aggregate over brand-new tables and should
    // never be able to take /stats down; wrapped the same defensive way a
    // partial/pre-migration database is handled elsewhere in this route.
    let sweep = null;
    try {
      sweep = sweepStatus(db);
    } catch {
      sweep = null;
    }
    // lookupStatus is a plain aggregate over brand-new tables, same
    // defensive wrap as sweep above -- a missing/pre-migration lookup
    // schema must never take /stats down.
    let lookup = null;
    try {
      lookup = lookupStatus(db);
    } catch {
      lookup = null;
    }
    // lintStatus is a plain aggregate over brand-new tables, same defensive
    // wrap as sweep/lookup above -- a missing/pre-migration lint schema must
    // never take /stats down.
    let lint = null;
    try {
      lint = lintStatus(db);
    } catch {
      lint = null;
    }
    // cardStats is a plain aggregate over rm_card_event, same defensive wrap
    // as sweep/lookup/lint above -- a missing/pre-migration rm_card_event
    // table must never take /stats down.
    let cards = null;
    try {
      cards = cardStats(db, { now: Date.now() });
    } catch {
      cards = null;
    }
    send(res, 200,
      { rows: Number(n), memory: memoryProgress(db), peopleProjection: peopleProjectionStatus(db, policy), sweep, lookup, lint, cards },
      cors);
    return;
  }

  const gone = GONE.get(url.pathname);
  if (gone) {
    send(res, 410, { error: gone }, cors);
    return;
  }

  // Everything under /admin/ is lifecycle territory: dispatched as a prefix so
  // that an unknown admin path still meets the bearer-only gate before its 404
  // — a browser probing /admin/anything learns "not your channel", not a route
  // map.
  if (url.pathname.startsWith('/admin/')) {
    return handleAdmin(db, req, res, cors, url, channel, policy);
  }

  if (req.method === 'POST' && url.pathname === '/ingest') {
    // Authorization gates who may call; this gates what a permitted caller may
    // send. Match the media-type essence exactly: substring matching would
    // accept the CORS-safelisted `text/plain; x=application/json`, which is the
    // shape a page can POST with no preflight.
    if (!hasJsonMediaType(req)) {
      send(res, 415, { error: 'content-type must be application/json' }, cors);
      return;
    }
    return readJson(req).then((body) => {
      // insertRows returns exactly the response contract: how many rows were
      // new, how many replaced an entity in place, and how many were
      // redeliveries the canonical hash proved identical.
      const touchesPeople = (Array.isArray(body) ? body : [body])
        .some((row) => isProjectedPeopleSource(row?.source));
      const counts = insertRows(db, body);
      send(res, 200, counts, cors);
      if (touchesPeople && (counts.inserted > 0 || counts.updated > 0)) {
        schedulePeopleProjectionRefresh(db);
      }
    });
  }

  // The lane is the path. Not a header and not a body field: a header would
  // have to be added to Access-Control-Allow-Headers, and forgetting that
  // breaks every preflight and surfaces inside the client as "Hermes is down";
  // a body field would be a default waiting to be inferred. A path cannot be
  // omitted, and a garbled one 404s instead of quietly picking a lane.
  //
  // There is deliberately no unlaned alias. `/v1/chat/completions` is 410, not
  // a redirect to local -- an alias IS the unlaned default this exists to
  // remove.
  if (req.method === 'POST' && url.pathname === '/vault/ask') {
    return handleVaultAsk(db, req, res, cors, policy);
  }

  if (req.method === 'POST' && url.pathname === '/lane/local/v1/chat/completions') {
    if (!hasJsonMediaType(req)) {
      send(res, 415, { error: 'content-type must be application/json' }, cors);
      return;
    }
    return proxyLlama(req, res, cors, policy.llama);
  }

  // Refuses loudly rather than falling back to local. A silent downgrade would
  // make the lane gate look like it works when it does not, and the first
  // person to wire an address signal without a cloud client needs to find out
  // on the first addressed utterance -- not from a metric six weeks later.
  if (req.method === 'POST' && url.pathname === '/lane/cloud/v1/chat/completions') {
    send(res, 501, { error: 'the cloud lane is not built' }, cors);
    return;
  }

  // People / Phase 1 — the "initialize search" backend and its identity-review
  // queue. Bearer-only, like /admin: these read the whole corpus into a people
  // map and WRITE the owner's merge decisions, neither of which is a browser
  // capability. The Origin channel is authenticated but not entitled here, so
  // 403 (not 401), matching handleAdmin's reasoning.
  if (url.pathname === '/people/find' || url.pathname === '/people/init' || url.pathname === '/people/review' || url.pathname === '/people/decide' || url.pathname === '/people/self' || url.pathname === '/people/role' || url.pathname === '/people/sub-roles' || url.pathname === '/people/map' || url.pathname === '/people/year' || url.pathname === '/people/avatars') {
    if (channel !== 'bearer') {
      send(res, 403, { error: 'people routes are bearer-only: call with the token from ~/.hazlie/secrets/hermes-token.txt and no Origin header.' }, cors);
      return;
    }
    return handlePeople(db, req, res, cors, url, policy);
  }

  send(res, 404, { error: `no route for ${req.method} ${url.pathname}` }, cors);
}

// Closed field sets for the /people POST bodies — the same discipline as
// every other write route here: a typo'd key ({day: 30}) must 400, not
// silently build the all-time map.
const PEOPLE_INIT_FIELDS = Object.freeze(['days']);
const PEOPLE_DECIDE_FIELDS = Object.freeze(['verdict', 'a', 'b']);
const PEOPLE_SELF_FIELDS = Object.freeze(['key']);
const PEOPLE_ROLE_FIELDS = Object.freeze(['key', 'role', 'year']);
const PEOPLE_SUB_ROLES_FIELDS = Object.freeze(['personKey', 'subRoles']);
const PEOPLE_YEAR_COMPLETION_FIELDS = Object.freeze(['year']);

// Phase 1 routes. init and review both build the people map and return the
// pairs still needing the owner's eyes; decide records one call. Split out so
// handle() stays a flat dispatch table.
async function handlePeople(db, req, res, cors, url, policy) {
  const owner = loadOwner();

  // Timeframe in days back (0 = all time), from the popup's selector. Clamped to
  // a decade so a fat-fingered value can't ask for an epoch before the corpus.
  const parseDays = (raw) => {
    if (raw === null || raw === undefined || raw === '') return 0;
    const n = Number(raw);
    if (!Number.isInteger(n) || n < 0 || n > 3650) throw badRequest('"days" must be an integer 0..3650 (0 = all time)');
    return n;
  };
  const parseLimit = (raw) => {
    if (raw === null || raw === undefined || raw === '') return 40;
    const n = Number(raw);
    if (!Number.isInteger(n) || n < 1 || n > 100) throw badRequest('"limit" must be an integer 1..100');
    return n;
  };

  if (req.method === 'POST' && url.pathname === '/people/init') {
    if (!hasJsonMediaType(req)) { send(res, 415, { error: 'content-type must be application/json' }, cors); return; }
    const body = await readJson(req);
    assertClosedFields(body, PEOPLE_INIT_FIELDS);
    const days = parseDays(body?.days);
    const out = withPeopleDbs(db, (state, resDb) => peopleReview(db, state, resDb, { days, owner }));
    send(res, 200, out, cors);
    return;
  }

  if (req.method === 'GET' && url.pathname === '/people/review') {
    const days = parseDays(url.searchParams.get('days'));
    const limit = parseLimit(url.searchParams.get('limit'));
    const out = withPeopleDbs(db, (state, resDb) => peopleReview(db, state, resDb, { days, owner, limit }));
    send(res, 200, out, cors);
    return;
  }

  // An owner can correct the graph when one of their own aliases has appeared
  // as a relationship. Find the key in the local graph before writing it, so a
  // page cannot stuff arbitrary values into the connector config. The correction
  // records the stable key and any address-shaped identifiers, then rebuilds the
  // cached core before the UI's next read.
  if (req.method === 'POST' && url.pathname === '/people/self') {
    if (!hasJsonMediaType(req)) { send(res, 415, { error: 'content-type must be application/json' }, cors); return; }
    const body = await readJson(req);
    assertClosedFields(body, PEOPLE_SELF_FIELDS);
    if (typeof body?.key !== 'string' || body.key.length === 0 || body.key.length > 300) {
      throw badRequest('"key" must be a person key');
    }
    const marked = withPeopleDbs(db, (state, resDb) => {
      const { aliases } = resolutionState(resDb);
      const person = materializedPeopleGraph(db, state, { owner, aliases }).find((candidate) => candidate.key === body.key);
      if (!person) throw badRequest('"key" is not a current person');
      return markOwnerPerson({ key: person.key, identifiers: person.identifiers });
    });
    rebuildPeopleCore(db);
    send(res, 200, { state: 'ok', ...marked }, cors);
    return;
  }

  if (req.method === 'POST' && url.pathname === '/people/role') {
    if (!hasJsonMediaType(req)) { send(res, 415, { error: 'content-type must be application/json' }, cors); return; }
    const body = await readJson(req);
    assertClosedFields(body, PEOPLE_ROLE_FIELDS);
    if (typeof body?.key !== 'string' || body.key.length === 0 || body.key.length > 300) {
      throw badRequest('"key" must be a person key');
    }
    if (!['friend', 'business', 'romantic', 'family'].includes(body?.role)) {
      throw badRequest('"role" must be friend, business, romantic, or family');
    }
    if (body?.year !== undefined && (!Number.isInteger(body.year) || body.year < 1900 || body.year > 3000)) {
      throw badRequest('"year" must be an integer from 1900 through 3000');
    }
    const marked = withPeopleDbs(db, (state, resDb) => {
      const { aliases } = resolutionState(resDb);
      const person = materializedPeopleGraph(db, state, { owner, aliases }).find((candidate) => candidate.key === body.key);
      if (!person) throw badRequest('"key" is not a current person');
      return markPersonRole({ key: person.key, role: body.role, year: body.year ?? null });
    });
    rebuildPeopleCore(db);
    send(res, 200, { state: 'ok', ...marked }, cors);
    return;
  }

  // The owner's correction for the eligibility producer's investor/founder
  // mode filter (relationship/producer.mjs): same shape and posture as
  // /people/role above, just a different override map (personSubRoles,
  // subRoles.mjs's subRolesFor) and a closed three-value set instead of a
  // closed four-value one. An empty array is accepted and means "none of
  // these" -- not "no correction" -- so the override always wins once the
  // owner has made this call for a person, even to clear every tag.
  if (req.method === 'POST' && url.pathname === '/people/sub-roles') {
    if (!hasJsonMediaType(req)) { send(res, 415, { error: 'content-type must be application/json' }, cors); return; }
    const body = await readJson(req);
    assertClosedFields(body, PEOPLE_SUB_ROLES_FIELDS);
    if (typeof body?.personKey !== 'string' || body.personKey.length === 0 || body.personKey.length > 300) {
      throw badRequest('"personKey" must be a person key');
    }
    if (!Array.isArray(body?.subRoles) || !body.subRoles.every((role) => typeof role === 'string' && SUB_ROLE_VALUES.includes(role))) {
      throw badRequest(`"subRoles" must be an array drawn from: ${SUB_ROLE_VALUES.join(', ')}`);
    }
    const marked = withPeopleDbs(db, (state, resDb) => {
      const { aliases } = resolutionState(resDb);
      const person = materializedPeopleGraph(db, state, { owner, aliases }).find((candidate) => candidate.key === body.personKey);
      if (!person) throw badRequest('"personKey" is not a current person');
      return markPersonSubRoles({ key: person.key, subRoles: body.subRoles });
    });
    rebuildPeopleCore(db);
    send(res, 200, { ok: true, personKey: marked.key, subRoles: marked.subRoles }, cors);
    return;
  }

  // The constellation: every person as a star, clustered and lit. Folds in the
  // owner's confirmed merges (aliases) so a merged person is one star.
  if (req.method === 'GET' && url.pathname === '/people/map') {
    const days = parseDays(url.searchParams.get('days'));
    const sinceTs = days > 0 ? Date.now() - days * 86_400_000 : null;
    const out = withPeopleDbs(db, (state, resDb) => {
      const { aliases } = resolutionState(resDb);
      if (url.searchParams.get('rebuild') === '1') rebuildPeopleCore(db);
      const map = buildMap(db, state, { owner, sinceTs, aliases });
      return { ...map, freshness: peopleCoreFreshness(db, state, aliases, owner) };
    });
    // PROJECTED, NOT JUST STRIPPED.
    //
    // This route was CLI-only until the constellation started calling it from
    // the panel. Its star carries 22 fields including every handle a person has
    // -- 2,665 of them, 506 address-shaped and 1,859 phone-shaped -- and the page
    // reads eight. So `?for=page` returns those eight.
    //
    // Two reasons, and the second is the one that bites. Identifiers have no
    // business crossing into a webview: both sibling routes already strip them,
    // /people/find explicitly and with a comment. And SIZE -- the full payload is
    // 1.32 MB, and Bridge.reply hands it to evaluateJavaScript as one inlined
    // string with completionHandler nil, so if the web view refuses it the
    // failure is discarded and the page simply never receives its data. A
    // surface that fails by going quiet is worth 5x less bytes on its own.
    //
    // Unprojected stays the default so the CLI and any existing caller are
    // unchanged; the page asks for what it needs.
    const forPage = url.searchParams.get('for') === 'page';
    const people = (out.people ?? []).map(({ identifiers, ...star }) => {
      if (!forPage) return star;
      return {
        key: star.key,
        name: star.name,
        channels: star.channels,
        messages: star.messages,
        roomMessages: star.roomMessages,
        roomOnly: star.roomOnly,
        role: star.role,
        presenceDays: star.presenceDays,
        lastSeen: star.lastSeen,
        years: star.years,
      };
    });
    send(res, 200, { ...out, people }, cors);
    return;
  }

  // The timeline view: one year of people by that year's engagement, with
  // the year's topics. Same auth posture as map.
  // FINDING A PERSON, across every year rather than whichever tab is open.
  //
  // The timeline filtered client-side over the 250 people already loaded for one
  // year, so anybody outside that page or that year was unreachable -- which is
  // most people once history lands. Ranking lives in people/find.mjs and is
  // arithmetic: no model is in this path, because a search that invents a person
  // is worse than one that finds nobody.
  if (req.method === 'GET' && url.pathname === '/people/find') {
    const q = url.searchParams.get('q') ?? '';
    if (typeof q !== 'string' || q.length > 100) {
      throw badRequest('"q" must be a string of at most 100 characters');
    }
    const out = withPeopleDbs(db, (state, resDb) => {
      const { aliases } = resolutionState(resDb);
      const { byYear, years, idToKey } = buildSearchYears(db, state, { owner, aliases });
      // The corpus half: who actually talked about this, counted per person-year
      // (people/content.mjs). Counts only — no message text crosses this line.
      const { stats, capped } = contentMatches(db, idToKey, q);
      const people = rankAcrossYears(byYear, q, { limit: 60, content: stats }).map(
        // The handles matched the query; they are not part of the answer, and
        // the page has no use for them.
        ({ identifiers, engagement, ...row }) => row
      );
      return { query: q, years, people, capped };
    });
    send(res, 200, out, cors);
    return;
  }

  if (req.method === 'GET' && url.pathname === '/people/year') {
    const raw = url.searchParams.get('year');
    const thisYear = new Date().getFullYear();
    const year = raw === null || raw === '' ? thisYear : Number(raw);
    if (!Number.isInteger(year) || year < 1990 || year > thisYear + 1) {
      throw badRequest(`"year" must be an integer 1990..${thisYear + 1}`);
    }
    const out = withPeopleDbs(db, (state, resDb) => {
      const { aliases } = resolutionState(resDb);
      if (url.searchParams.get('rebuild') === '1') rebuildPeopleCore(db);
      // The ordinary page is capped for fast paint. A relationship-label
      // navigation explicitly asks for every matching person in this year, so
      // its bridge request upgrades the year payload to the full ranked set.
      const all = url.searchParams.get('all') === '1';
      const year_ = buildYear(db, state, { year, owner, aliases, cap: all ? Infinity : 250 });
      // HOW OLD IS THIS ANSWER. The core serves stale and rebuilds behind the
      // response, which is what makes the page instant -- but an answer that is
      // one ingest behind must say so rather than pass as live.
      return { ...year_, freshness: peopleCoreFreshness(db, state, aliases, owner) };
    });
    send(res, 200, out, cors);
    return;
  }

  // Contact photos are delivered through the native bridge: widget pages have
  // no bearer token and therefore cannot fetch Hermes URLs themselves.
  if (req.method === 'POST' && url.pathname === '/people/avatars') {
    if (!hasJsonMediaType(req)) { send(res, 415, { error: 'content-type must be application/json' }, cors); return; }
    const body = await readJson(req);
    assertClosedFields(body, ['keys']);
    const keys = Array.isArray(body.keys) ? body.keys.filter((k) => typeof k === 'string').slice(0, 400) : [];
    const out = withPeopleDbs(db, (state, resDb) => {
      const { aliases } = resolutionState(resDb);
      const avatars = {};
      for (const [key, jpeg] of buildAvatars(db, state, { keys, owner, aliases })) {
        avatars[key] = Buffer.from(jpeg).toString('base64');
      }
      return { avatars };
    });
    send(res, 200, out, cors);
    return;
  }

  if (req.method === 'POST' && url.pathname === '/people/decide') {
    if (!hasJsonMediaType(req)) { send(res, 415, { error: 'content-type must be application/json' }, cors); return; }
    const body = await readJson(req);
    assertClosedFields(body, PEOPLE_DECIDE_FIELDS);
    const verdict = body?.verdict;
    if (verdict !== 'same' && verdict !== 'different' && verdict !== 'skip') {
      throw badRequest('"verdict" must be one of same, different, skip');
    }
    if (typeof body?.a !== 'string' || typeof body?.b !== 'string' || !body.a || !body.b || body.a === body.b) {
      throw badRequest('"a" and "b" must be two distinct person keys');
    }
    const out = withPeopleDbs(db, (_state, resDb) => peopleDecide(resDb, { a: body.a, b: body.b, verdict }));
    send(res, 200, out, cors);
    return;
  }

  send(res, 404, { error: `no route for ${req.method} ${url.pathname}` }, cors);
}

// Tests start this on an ephemeral port with a throwaway DB; the CLI entry at
// the bottom starts it with the real defaults. Returns once listening.
//
// `async` so that a missing secret file rejects rather than throwing
// synchronously. It used to throw: the key validation below runs before the
// listen promise is constructed, so `start().then(ok, fail)` at the bottom of
// this file never reached `fail` and a fresh machine got a raw stack trace
// instead of the sentence naming the fix. Two secrets to provision now, so the
// path is twice as easy to land on.
export async function start({
  // 51789, not 8787: the canonical port moved on 2026-08-20 (MEMORY-PLAN Day 0)
  // because an unrelated dev server holds 8787 on the owner's Mac and answers
  // 200 there, which made every defaulted caller reach a stranger. One number,
  // set here and echoed by DEFAULT_HERMES_BASE_URL in connectors/lib/
  // ingestClient.mjs and the probe in ops/setup-connectors.sh — change all
  // three together or not at all.
  port = Number(process.env.HERMES_PORT ?? 51789),
  dbPath,
  allowedOrigins = process.env.HERMES_ALLOWED_ORIGINS,
  llamaBaseUrl = process.env.HERMES_LLAMA_URL ?? DEFAULT_LLAMA_BASE_URL,
  llamaApiKey,
  llamaApiKeyFile = process.env.HERMES_LLAMA_API_KEY_FILE ?? DEFAULT_LLAMA_API_KEY_PATH,
  // Test seam only: the ask's ceiling. Production never passes it, so the
  // constant is the one number that matters and there is no env var to drift.
  askTimeoutMs = ASK_TIMEOUT_MS,
  bearerToken: fixedBearerToken,
  bearerTokenFile = process.env.HERMES_TOKEN_FILE ?? DEFAULT_HERMES_TOKEN_PATH,
  // Test seams for the relationship card routes: a stub matcher (no llama),
  // a fixed cap, and a fixed producer selection (production reads all three
  // from the owner's config).
  relationshipMatcher,
  relationshipCap,
  relationshipProducerConfig,
  // Test seam for the person-page builder: a pre-built `{name, complete}`
  // engine, so a route test never spawns the real claude CLI or reaches
  // loopback llama-server. Production leaves this undefined and
  // relationshipMemoryEngine() reads the owner's config file per call.
  relationshipMemoryEngine: relationshipMemoryEngineOverride,
  // Test seam for public lookup (L5 step 6): a pre-built `{name, complete}`
  // engine (or null, to exercise the no-engine path), same discipline as
  // relationshipMemoryEngine above. Production leaves this undefined and
  // relationshipLookupEngine() reads the owner's config file per call.
  relationshipLookupEngine: relationshipLookupEngineOverride,
  // Test seam: production always wants the eager rebuild (see
  // schedulePeopleRebuild); a test asserting synchronous post-clear/purge
  // emptiness opts out rather than the production default changing for it.
  peopleProjectionAutoRebuild = true,
  llamaModel = process.env.HAZLIE_MAIN_MODEL,
} = {}) {
  const allowedOriginSet = parseAllowedOrigins(allowedOrigins);
  let apiKey;
  if (llamaApiKey === undefined) {
    // Fail startup early, then re-read per request so setup can rotate the key
    // without leaving a long-running Hermes process stuck on the old value.
    readLlamaApiKey(llamaApiKeyFile);
    apiKey = () => readLlamaApiKey(llamaApiKeyFile);
  } else {
    const fixedApiKey = validateHexKey(llamaApiKey, 'llama API key');
    apiKey = () => fixedApiKey;
  }
  // Same discipline as the llama key: validate once so a missing token is a
  // startup failure with a fix in the message, then re-read per request so
  // rotation does not need a restart. Only the bearer channel pays that read --
  // browser requests are authorized by Origin and never touch the file, so the
  // voice loop's per-turn path does no filesystem work here.
  let bearerToken;
  if (fixedBearerToken === undefined) {
    readHermesToken(bearerTokenFile);
    bearerToken = () => readHermesToken(bearerTokenFile);
  } else {
    const token = validateHexKey(fixedBearerToken, 'Hermes bearer token');
    bearerToken = () => token;
  }
  const llama = {
    baseUrl: canonicalLoopbackBase(llamaBaseUrl),
    apiKey,
    ...(llamaModel ? { model: llamaModel } : {}),
  };
  const askCeilingMs = Number.isFinite(askTimeoutMs) && askTimeoutMs > 0
    ? askTimeoutMs
    : ASK_TIMEOUT_MS;
  // Stable across requests: the per-request policy object cannot carry cached
  // state, and the relationship service (spine handle, resolutions handle,
  // current card batch) must live for the process, not the request.
  const relationshipHolder = {};
  // Same reasoning, for the eager people-projection rebuild: rebuilding/
  // lastRebuildError must survive across the requests that trigger and poll
  // it (schedulePeopleRebuild, and GET /stats).
  const peopleProjectionHolder = {};
  const configuredDbPath = dbPath ?? process.env.HERMES_DB;
  const resolvedDbPath = configuredDbPath ?? DEFAULT_DB_PATH;
  // Summary generation was retired. Remove its private derived database and
  // SQLite sidecars once the replacement process starts so old model prose is
  // not left behind indefinitely. These are exact legacy paths, never a
  // directory or wildcard.
  removeRetiredPeopleSummaries(configuredDbPath, resolvedDbPath);
  const db = openDb(resolvedDbPath);
  // The cache is derived and rebuildable, so keep it beside the exact corpus
  // handle it accelerates. In-memory test databases get no implicit disk
  // writes. The store persists only hashed inputs and constrained outputs.
  const databaseFile = db.prepare('PRAGMA database_list').get()?.file ?? '';
  const peopleSearchCachePath = databaseFile ? `${databaseFile}.people-search-cache` : null;
  const peopleSearchCache = peopleSearchCachePath
    ? openPeopleSearchCache(peopleSearchCachePath)
    : null;
  const server = createServer(async (req, res) => {
    const cors = corsHeaders(req, allowedOriginSet);

    if (req.method === 'OPTIONS') {
      res.writeHead(204, { ...PRIVATE_RESPONSE_HEADERS, ...cors });
      res.end();
      return;
    }

    // Host is attacker-controlled bytes and a space in it is a legal header
    // value that WHATWG URL rejects; an unguarded parse here is an unhandled
    // rejection that kills the household's 24/7 memory process.
    let url;
    try {
      url = new URL(req.url, `http://${req.headers.host ?? 'localhost'}`);
    } catch {
      send(res, 400, { error: 'unparseable request URL' }, cors);
      return;
    }

    try {
      await handle(db, req, res, cors, url, {
        allowedOrigins: allowedOriginSet,
        bearerToken,
        llama,
        peopleSearchCache,
        peopleSearchCachePath,
        relationshipMatcher,
        relationshipCap,
        relationshipProducerConfig,
        relationshipMemoryEngine: relationshipMemoryEngineOverride,
        relationshipLookupEngine: relationshipLookupEngineOverride,
        relationshipHolder,
        peopleProjectionHolder,
        peopleProjectionAutoRebuild,
      });
    } catch (e) {
      send(res, e.status ?? 500, { error: e.message ?? String(e) }, cors);
    }
  });

  return new Promise((resolve, reject) => {
    server.once('error', reject);
    server.listen(port, '127.0.0.1', () => {
      // A projection left at -1/0 by a purge that ran before the last
      // restart (or a fresh install) would otherwise sit empty until the
      // People page or a search happened to ask for it. Read-only and
      // skipped on any error -- a missing/unreadable state table means
      // nothing to correct here, not a startup failure.
      try {
        const state = projectionState(db);
        if (!state || Number(state.projected_revision) < 0 || Number(state.people_count) === 0) {
          schedulePeopleRebuild(db, { peopleProjectionHolder, peopleProjectionAutoRebuild }, 'startup');
        }
      } catch {}
      resolve({
        server,
        db,
        port: server.address().port,
        close: () =>
          new Promise((done, fail) => {
            server.close(async (err) => {
              try {
                peopleSearchCache?.close();
                db.close();
                err ? fail(err) : done();
              } catch (closeError) {
                fail(closeError);
              }
            });
          }),
      });
    });
  });
}

const isMain =
  process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;

if (isMain) {
  start().then(
    ({ port, db }) => {
      const { n } = db.prepare('SELECT count(*) AS n FROM context').get();
      console.log(
        `hermes listening on http://127.0.0.1:${port} (context rows: ${n})`
      );
      // WARM THE PEOPLE CORE BEFORE ANYBODY ASKS.
      //
      // The first build is the one wait that cannot be served around: ~7.6s of
      // synchronous work with nothing cached to hand back instead. Every hermes
      // restart throws the memo away, and the app restarts hermes on every
      // deploy — so without this, the first person to open the panel after a
      // deploy pays it, every time, and while they wait hermes answers nothing
      // at all (node:sqlite is synchronous; a 20ms timer got zero ticks during
      // an 8s build).
      //
      // Deferred past listen so the port is open first: a request arriving
      // during the warm is queued behind it, which is the same wait it would
      // have paid anyway, and /health answers before it starts.
      //
      // Counts only in the log, and failure is not fatal: an unwarmed core is
      // slow, not broken, and the next request builds it.
      setTimeout(() => {
        const t0 = Date.now();
        try {
          // A DERIVED CACHE, beside the corpus it is derived from -- the path
          // asked of the handle rather than recomputed, so it always names the
          // database actually open and an in-memory one (which reports no file)
          // gets no cache at all. Deleting it costs one rescan and nothing
          // else, which is the only property it needs to have. Opened here
          // rather than at import so a test that imports the module never
          // writes to the owner's disk.
          const file = db.prepare('PRAGMA database_list').get()?.file ?? '';
          if (file) useTallyStore(openTallyStore(`${file}.tallies`));
          const core = warmPeopleCore(db);
          console.log(
            `people core warm in ${Date.now() - t0}ms (${core?.graph?.length ?? 0} people)`
          );
        } catch (e) {
          console.error(`people core warm failed: ${e?.message ?? e}`);
        }
      }, 250).unref?.();
    },
    (e) => {
      console.error(`hermes failed to start: ${e.message ?? e}`);
      process.exit(1);
    }
  );
}
