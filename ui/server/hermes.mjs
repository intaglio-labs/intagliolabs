// Bumped only when a migration must run at open. Version history:
//   1  secure_delete zeroes pages freed AFTER it is switched on, so a database
//      created before it was set still has legible text in its free list, and
//      only a full VACUUM rewrites those pages. Marking the rewrite means it
//      happens once rather than on every boot of a 24/7 process.
//   2  entity_id + content_hash columns and the partial UNIQUE index that turn
//      connector redelivery into an upsert instead of a duplicate row.
//   3  store_changed_at: a real ingestion cursor, because `ts` is event time
//      and moves backwards. Plus FTS5 secure-delete on both indexes.
//   4  claim_fts rebuilt with the porter stemmer, which unifies plurals and
//      verb forms. It is a partial win only -- see the note in SCHEMA.
//   5  the entity uniqueness key becomes (source, entity_id) -- ids are only
//      unique within a source; the incident is recorded on the v5 branch.
//  10  Hermes-owned materialized people, identifiers, identity evidence, and
//      activity tables. Raw context remains the rebuildable source of truth.
//   9  claim.valid_to: a plan or commitment can finally say which day it was
//      about. A private corpus showed that many old intentions were otherwise
//      ageing exactly like standing facts.
//   8  episode + episode_member, and distill_run.episode_context recording
//      which arm produced a run. The episode is a derived grouping of context
//      rows; the arm column is what makes turning received-message context on
//      revertible by one index scan instead of an argument.
//   7  distill_run.through_id: the distiller's cursor becomes (store_changed_at,
//      id). It was store_changed_at alone, described as strictly monotonic and
//      measurably not -- connector batches share timestamps -- so a capped
//      pass advanced past the rest of its tie group and eligible rows were
//      never read.
//   6  context_source_ts(source, ts, entity_id): per-source time-range reads
//      (reconciliation slices, retain sweeps, the episodic shelf, the digest
//      aggregate, the watchdog's max(ts)) all scanned without it.
//  11  claim.subject widens to ('owner','person') plus subject_person_key --
//      L5 step 2. A CHECK cannot be ALTERed, so the claim table is rebuilt in
//      place with ids preserved. RENUMBERED from 10: the deep-search branch
//      claimed 10 independently and shipped first, and a development open of
//      that branch stamped the reference install's database at 10 while this
//      branch's rebuild had not run -- the incident that made the rebuild key
//      on the DDL rather than on this number (see rebuildClaimTableForV10).
//      Two branches bumping the same version is exactly how a stamp comes to
//      lie; the DDL check is why it no longer matters when one does.
//  12  person_sweep_cursor, person_sweep_run, person_sweep_proposal (L5 step
//      5, the discovery sweep). All three are brand-new tables created by
//      SCHEMA's own IF NOT EXISTS, so nothing here ALTERs anything; the
//      version < 12 branch below only (re-)asserts their indexes, same
//      belt-and-suspenders posture as the ALTER-guarded branches above.
//  13  person_lookup_state, person_lookup_run, lookup_log, person_lookup_change
//      (L5 step 6, public lookup). All four are brand-new tables created by
//      SCHEMA's own IF NOT EXISTS, so nothing here ALTERs anything; the
//      version < 13 branch below only (re-)asserts their indexes.
const SCHEMA_VERSION = 13;

// The PRAGMAs that decide whether "deleted" means deleted, and whether the
// memory tables' declared references mean anything. Applied to every
// connection, including :memory:, which previously skipped all hardening.
function hardenConnection(db) {
  // Declaring a foreign key while leaving enforcement off is documentation,
  // not integrity -- and SQLite's default is OFF, per connection, every time.
  // The claim tables are the first in this database to declare any, so this
  // has no effect on the context-only paths that predate them.
  //
  // It does NOT make ON DELETE CASCADE safe to lean on for FTS cleanup:
  // whether a cascade fires the AFTER DELETE trigger that tombstones
  // claim_fts depends on recursive_triggers, which nothing here sets. The
  // deletion paths below therefore issue explicit ordered DELETEs instead.
  db.exec('PRAGMA foreign_keys = ON');
  // Zero freed pages instead of leaving the text legible in the free list.
  db.exec('PRAGMA secure_delete = ON');
  // Wait for a held lock instead of failing instantly. SQLite's default is 0:
  // any contention raises SQLITE_BUSY immediately, and there is contention
  // here — hermes is the only WRITER, but distill-once, the digest and the
  // sealed reader all open this database, and a blocking VACUUM from
  // /admin/maintain holds an exclusive lock for as long as it takes.
  // 5s matches ops/probes/probe-wal-read.mjs, which is the only other place in
  // this repo that sets it against this database. A reader that waits is
  // correct; a reader that throws mid-poll loses that poll's rows.
  db.exec('PRAGMA busy_timeout = 5000');
  // Keep a VACUUM's temp file in memory rather than in a directory whose mode
  // we do not control.
  db.exec('PRAGMA temp_store = MEMORY');
  // Persistent in the file header, so it binds every future connection too.
  // Without it a -wal/-shm sidecar holds the same household text at whatever
  // mode SQLite chose -- and openDb only ever chmods the main database file.
  db.exec('PRAGMA journal_mode = DELETE');
}

function migrate(db) {
  const row = db.prepare('PRAGMA user_version').get();
  let version = Number(row?.user_version ?? 0);
  // THE STAMP IS A CACHE; THE DDL IS THE TRUTH. Found 2026-08-29 on the
  // reference install: the live database was stamped user_version 10 while
  // still carrying the v9 claim table -- an open running mid-development
  // branch code stamped without rebuilding, and every later open trusted the
  // stamp and skipped the rebuild forever, which surfaces as 'no such
  // column: c.subject_person_key' the first time pendingClaims runs. The v2
  // migration already learned this lesson for ALTERs ("guarded by what
  // table_info actually reports rather than by version arithmetic"); this
  // applies it to the rebuild: the check runs on every open, costs one
  // sqlite_master read, and heals a mis-stamped database no matter what the
  // version says.
  rebuildClaimTableForV10(db);
  if (version >= SCHEMA_VERSION) return;
  if (version < 1) {
    // Rewrites every page under secure_delete. Cheap on a small database and
    // cheapest of all on an empty one; do not defer it to a purge path, because
    // the pages needing the rewrite are the ones a purge already freed.
    db.exec('VACUUM');
    version = 1;
  }
  if (version < 2) {
    // A FRESH database reaches this branch too (SCHEMA created it at
    // user_version 0 already carrying both columns), so each ALTER is guarded
    // by what table_info actually reports rather than by version arithmetic.
    const columns = new Set(
      db.prepare("SELECT name FROM pragma_table_info('context')").all().map((c) => c.name)
    );
    if (!columns.has('entity_id')) db.exec('ALTER TABLE context ADD COLUMN entity_id TEXT');
    if (!columns.has('content_hash')) db.exec('ALTER TABLE context ADD COLUMN content_hash TEXT');
    // This index lives here and NOT in SCHEMA: SCHEMA executes before migrate
    // on every open, and on a v1 database entity_id does not exist until the
    // ALTER above runs — an index statement in SCHEMA would fail the open of
    // exactly the databases this migration exists to upgrade. Partial, so the
    // identity-less rows (entity_id NULL) never collide with one another.
    db.exec(
      'CREATE UNIQUE INDEX IF NOT EXISTS context_entity ON context(entity_id) WHERE entity_id IS NOT NULL'
    );
    version = 2;
  }
  if (version < 3) {
    const columns = new Set(
      db.prepare("SELECT name FROM pragma_table_info('context')").all().map((c) => c.name)
    );
    if (!columns.has('store_changed_at')) {
      db.exec('ALTER TABLE context ADD COLUMN store_changed_at INTEGER');
    }
    // BACKFILL WITH THE MIGRATION INSTANT, NOT `ts`. This is the whole reason
    // the column exists: `ts` is event time and future-dated calendar rows are
    // valid. A
    // cursor seeded from those would sit weeks ahead of the present and skip
    // every real write until the calendar caught up with it.
    db.prepare('UPDATE context SET store_changed_at = ? WHERE store_changed_at IS NULL').run(
      Date.now()
    );
    // Here and not in SCHEMA, for the same reason context_entity is here: on a
    // pre-v3 database the column does not exist until the ALTER above runs, so
    // an index statement in SCHEMA would fail the open of exactly the
    // databases this migration exists to upgrade.
    db.exec('CREATE INDEX IF NOT EXISTS context_changed ON context(store_changed_at, id)');
    // FTS5's ordinary delete leaves the old term entries legible inside the
    // index's own pages until a rebuild rewrites them. secure-delete zeroes
    // them as it goes. It is a persistent setting in each index's %_config
    // table, so this runs once at migration rather than on every open.
    //
    // context_fts gets it too, though only claim_fts is new. It was missing
    // there — the connection-level secure_delete PRAGMA does not reach inside
    // an FTS5 index — so the corpus index has been leaving deleted household
    // text legible until the next /admin/maintain. Fixing it alongside is a
    // strict improvement and costs one statement; flagged in the handoff
    // rather than slipped in silently.
    db.exec(`INSERT INTO context_fts(context_fts, rank) VALUES('secure-delete', 1)`);
    db.exec(`INSERT INTO claim_fts(claim_fts, rank) VALUES('secure-delete', 1)`);
    version = 3;
  }
  if (version < 4) {
    // Recreate rather than ALTER: an FTS5 index's tokenizer is fixed at
    // creation. The triggers reference the table by NAME, so they keep working
    // across the swap and do not need dropping. `rebuild` repopulates from the
    // content table, which is `claim` -- no claim data lives in the index
    // itself, so nothing is lost by dropping it.
    const existing = db
      .prepare("SELECT sql FROM sqlite_master WHERE type = 'table' AND name = 'claim_fts'")
      .get();
    if (existing !== undefined && !/porter/iu.test(String(existing.sql))) {
      db.exec('DROP TABLE claim_fts');
      db.exec(
        "CREATE VIRTUAL TABLE claim_fts USING fts5(text, content='claim', content_rowid='id', tokenize='porter unicode61')"
      );
      db.exec(`INSERT INTO claim_fts(claim_fts) VALUES('rebuild')`);
      db.exec(`INSERT INTO claim_fts(claim_fts, rank) VALUES('secure-delete', 1)`);
    }
    version = 4;
  }
  if (version < 5) {
    // The uniqueness key becomes (source, entity_id).
    //
    // It was entity_id ALONE, which made the id globally unique across every
    // connector — but entity ids are only unique WITHIN a source.
    // connectors/AGENTS.md defines them per connector and shapes like
    // `health:<metric>:<YYYY-MM-DD>` collide across sources trivially. The
    // consequences ran in both directions and both were bad: the upsert's
    // SELECT matched the other source's row and OVERWROTE it in place, taking
    // that row's owner-accepted claims with it via
    // invalidateClaimsForChangedRow; and the overwritten row then belonged to
    // neither source, since /admin/delete-entities keys on (source,
    // entity_id) and no longer matched it.
    //
    // /admin/delete-entities has required both all along, with a comment
    // saying it does so "so a connector with a crossed-up id list cannot
    // delete another source's rows". The guard was on the harmless side and
    // absent from the destructive one. This aligns them.
    //
    // Safe to build: a private development corpus was checked for shared
    // entity_ids across sources and had none, so the narrower index had
    // nothing to reject. Verify this rather than assuming it — a UNIQUE index
    // that cannot be built fails the open of the database it should upgrade.
    db.exec('DROP INDEX IF EXISTS context_entity');
    db.exec(
      'CREATE UNIQUE INDEX IF NOT EXISTS context_entity ON context(source, entity_id) ' +
        'WHERE entity_id IS NOT NULL'
    );
    version = 5;
  }
  if (version < 6) {
    // Five recurring query shapes filter on source plus a ts range -- the
    // /admin/entities reconciliation slices (which also ORDER BY ts,
    // entity_id), /admin/retain's sweep, the episodic shelf's per-source
    // windows, the digest aggregate and the watchdog's per-source max(ts) --
    // and context_ts alone served none of them: each paid a near-full scan of
    // the ~340k-row live table on a single-threaded server. entity_id rides
    // along so the reconciliation slice comes off the index already in (ts,
    // entity_id) order, with no sort. Here and not in SCHEMA for the same
    // reason as context_entity: on a v1 database entity_id does not exist
    // until the v2 ALTER runs, so an index statement in SCHEMA would fail the
    // open of exactly the databases these migrations exist to upgrade.
    db.exec('CREATE INDEX IF NOT EXISTS context_source_ts ON context(source, ts, entity_id)');
    version = 6;
  }
  if (version < 7) {
    // The distiller's cursor gains its tie-breaker. Existing rows keep
    // through_id NULL, and distill-once reads NULL as 0 -- so the first pass
    // after this upgrade re-offers the whole tie group the old cursor stopped
    // inside, which is exactly the group it used to skip. Rows already
    // distilled come back as cache hits rather than model calls.
    const cols = new Set(
      db.prepare("SELECT name FROM pragma_table_info('distill_run')").all().map((c) => c.name)
    );
    if (!cols.has('through_id')) db.exec('ALTER TABLE distill_run ADD COLUMN through_id INTEGER');
    version = 7;
  }
  if (version < 8) {
    // episode/episode_member are created by SCHEMA above with IF NOT EXISTS.
    // Only the distill_run column needs an ALTER, and only because a column
    // cannot be added twice.
    const cols = new Set(
      db.prepare("SELECT name FROM pragma_table_info('distill_run')").all().map((c) => c.name)
    );
    if (!cols.has('episode_hash')) db.exec('ALTER TABLE distill_run ADD COLUMN episode_hash TEXT');
    db.exec('CREATE INDEX IF NOT EXISTS distill_run_episode ON distill_run(episode_hash)');
    if (!cols.has('episode_context')) {
      db.exec(
        "ALTER TABLE distill_run ADD COLUMN episode_context TEXT " +
          "CHECK (episode_context IN ('off','on'))"
      );
    }
    db.exec('CREATE INDEX IF NOT EXISTS distill_run_arm ON distill_run(episode_context, id)');
    version = 8;
  }
  if (version < 9) {
    const cols = new Set(
      db.prepare("SELECT name FROM pragma_table_info('claim')").all().map((c) => c.name)
    );
    if (!cols.has('valid_to')) db.exec('ALTER TABLE claim ADD COLUMN valid_to INTEGER');
    // Partial: only the rows that can expire carry a value, and those are the
    // only rows any query on it wants.
    db.exec(
      'CREATE INDEX IF NOT EXISTS claim_valid_to ON claim(valid_to) WHERE valid_to IS NOT NULL'
    );
    version = 9;
  }
  if (version < 10) {
    // The projection schema is ensured before migrate(), so fresh and upgraded
    // databases both have the tables here. The guarded ALTER also repairs a
    // short-lived development v9 schema that predated evidence confidence.
    const evidenceColumns = new Set(
      db.prepare("SELECT name FROM pragma_table_info('identity_evidence')").all().map((c) => c.name)
    );
    if (!evidenceColumns.has('confidence')) {
      db.exec(
        'ALTER TABLE identity_evidence ADD COLUMN confidence REAL NOT NULL DEFAULT 1 ' +
          'CHECK (confidence >= 0 AND confidence <= 1)'
      );
    }
    version = 10;
  }
  if (version < 11) {
    // The claim rebuild itself ran above, stamp or no stamp; this branch only
    // records the version. See rebuildClaimTableForV10.
    version = 11;
  }
  if (version < 12) {
    // person_sweep_cursor/_run/_proposal were already created above by SCHEMA
    // (CREATE TABLE IF NOT EXISTS, no pre-existing column to guard) -- this
    // branch exists only to (re-)assert their indexes, which is harmless
    // under IF NOT EXISTS, and to record the version.
    db.exec('CREATE INDEX IF NOT EXISTS person_sweep_run_started ON person_sweep_run(started_at)');
    db.exec('CREATE INDEX IF NOT EXISTS person_sweep_proposal_run ON person_sweep_proposal(run_id)');
    version = 12;
  }
  if (version < 13) {
    // person_lookup_state/_run, lookup_log, person_lookup_change were already
    // created above by SCHEMA (CREATE TABLE IF NOT EXISTS, no pre-existing
    // column to guard) -- this branch exists only to (re-)assert their
    // indexes, which is harmless under IF NOT EXISTS, and to record the
    // version.
    db.exec('CREATE INDEX IF NOT EXISTS person_lookup_state_due ON person_lookup_state(next_due_at)');
    db.exec('CREATE INDEX IF NOT EXISTS person_lookup_run_started ON person_lookup_run(started_at)');
    db.exec('CREATE INDEX IF NOT EXISTS lookup_log_person ON lookup_log(person_key, at DESC)');
    db.exec('CREATE INDEX IF NOT EXISTS person_lookup_change_log ON person_lookup_change(log_id)');
    version = 13;
  }
  db.exec(`PRAGMA user_version = ${SCHEMA_VERSION}`);
}

// claim.subject widens from the single literal 'owner' (L5 step 2). A CHECK
// constraint cannot be ALTERed in SQLite, so the table is rebuilt and rows
// copied with their ids -- claim_source and claim_decision reference
// claim(id), and preserved ids keep every receipt and every owner decision
// pointing where it pointed. Runs from migrate() on EVERY open, keyed on the
// DDL rather than on user_version -- see the incident note there.
//
// foreign_keys goes OFF first, and it is not ceremony: with enforcement
// ON, DROP TABLE performs an implicit DELETE whose foreign-key ACTIONS
// still run -- ON DELETE CASCADE on claim_source and claim_decision would
// empty both child tables. OFF, the drop is purely structural. The toggle
// is a no-op inside a transaction, which is why it brackets one rather
// than joining it.
function rebuildClaimTableForV10(db) {
    const claimDef = db
      .prepare("SELECT sql FROM sqlite_master WHERE type = 'table' AND name = 'claim'")
      .get();
    if (claimDef !== undefined && /subject\s*=\s*'owner'/u.test(String(claimDef.sql))) {
      // This runs BEFORE the numbered branches, so a pre-v9 database (v0.1.0
      // shipped at SCHEMA_VERSION 6) reaches it with no valid_to column yet
      // -- and the copy below names valid_to. The audit caught this as a
      // bricking bug: the copy threw 'no such column', the open failed, and
      // failed identically forever. The guarded ALTER is v9's own, done
      // early; v9's branch stays idempotent behind the same column check.
      const cols = new Set(
        db.prepare("SELECT name FROM pragma_table_info('claim')").all().map((c) => c.name)
      );
      if (!cols.has('valid_to')) db.exec('ALTER TABLE claim ADD COLUMN valid_to INTEGER');
      db.exec('PRAGMA foreign_keys = OFF');
      db.exec('BEGIN');
      try {
        db.exec(
          "CREATE TABLE claim_v10(" +
            'id INTEGER PRIMARY KEY, ' +
            'run_id INTEGER NOT NULL REFERENCES distill_run(id) ON DELETE CASCADE, ' +
            "subject TEXT NOT NULL CHECK (subject IN ('owner','person')), " +
            'subject_person_key TEXT CHECK ((subject_person_key IS NOT NULL) = (subject = \'person\')), ' +
            "kind TEXT NOT NULL CHECK (kind IN ('fact','preference','constraint','plan','commitment')), " +
            'text TEXT NOT NULL, observed_at INTEGER, valid_to INTEGER, p_claim REAL, ' +
            'created_at INTEGER NOT NULL)'
        );
        db.exec(
          'INSERT INTO claim_v10(id, run_id, subject, kind, text, observed_at, valid_to, p_claim, created_at) ' +
            'SELECT id, run_id, subject, kind, text, observed_at, valid_to, p_claim, created_at FROM claim'
        );
        // claim_fts goes FIRST, and not optionally: it is a content= index over
        // the table being dropped, and ALTER ... RENAME re-parses every schema
        // object that names the table -- with the fts index dangling, the
        // rename itself fails with a bare 'SQL logic error' (observed while
        // writing this migration). The v4 branch already established that the
        // index is disposable: no claim data lives in it, and 'rebuild'
        // repopulates it from the claim table it indexes.
        db.exec('DROP TABLE claim_fts');
        // v_claim_accepted references claim too, and it is the reason the fts
        // drop alone was not enough: ALTER ... RENAME re-parses EVERY schema
        // object, and a view naming a table that is mid-swap fails the whole
        // rename. Recreated verbatim below, same as the triggers.
        db.exec('DROP VIEW IF EXISTS v_claim_accepted');
        // Drops claim_run, claim_valid_to and the fts triggers with it.
        db.exec('DROP TABLE claim');
        db.exec('ALTER TABLE claim_v10 RENAME TO claim');
        db.exec(
          "CREATE VIRTUAL TABLE claim_fts USING fts5(text, content='claim', content_rowid='id', tokenize='porter unicode61')"
        );
        db.exec("INSERT INTO claim_fts(claim_fts) VALUES('rebuild')");
        // Re-assert secure-delete: it is a property of the (new) shadow
        // tables, not of the connection, and v3 set it for a reason.
        db.exec("INSERT INTO claim_fts(claim_fts, rank) VALUES('secure-delete', 1)");
        // Every trigger on the old table died with it, and SCHEMA will not
        // run again until the next open -- so ALL of them are recreated here,
        // verbatim, INCLUDING the append-only guards: a process that kept
        // running after this migration would otherwise accept its first
        // UPDATE on claim in the product's history.
        db.exec(
          'CREATE TRIGGER IF NOT EXISTS claim_ai AFTER INSERT ON claim BEGIN ' +
            'INSERT INTO claim_fts(rowid, text) VALUES (new.id, new.text); END'
        );
        db.exec(
          'CREATE TRIGGER IF NOT EXISTS claim_ad AFTER DELETE ON claim BEGIN ' +
            "INSERT INTO claim_fts(claim_fts, rowid, text) VALUES ('delete', old.id, old.text); END"
        );
        db.exec(
          'CREATE TRIGGER IF NOT EXISTS claim_no_update BEFORE UPDATE ON claim BEGIN ' +
            "SELECT RAISE(ABORT, 'claim is append-only: a correction appends a claim_decision or produces a new claim'); END"
        );
        db.exec(
          'CREATE TRIGGER IF NOT EXISTS claim_no_replace BEFORE INSERT ON claim ' +
            'WHEN new.id IS NOT NULL AND EXISTS (SELECT 1 FROM claim WHERE id = new.id) BEGIN ' +
            "SELECT RAISE(ABORT, 'claim is append-only: an explicit id colliding with an existing row is a REPLACE in disguise'); END"
        );
        db.exec('CREATE INDEX IF NOT EXISTS claim_run ON claim(run_id)');
        db.exec(
          'CREATE INDEX IF NOT EXISTS claim_valid_to ON claim(valid_to) WHERE valid_to IS NOT NULL'
        );
        db.exec(
          'CREATE VIEW IF NOT EXISTS v_claim_accepted AS ' +
            'SELECT c.* FROM claim c WHERE (' +
            'SELECT d.action FROM claim_decision d WHERE d.claim_id = c.id ' +
            "ORDER BY d.created_at DESC, d.id DESC LIMIT 1) = 'accept'"
        );
        db.exec('COMMIT');
      } catch (error) {
        db.exec('ROLLBACK');
        db.exec('PRAGMA foreign_keys = ON');
        throw error;
      }
      db.exec('PRAGMA foreign_keys = ON');
      // The receipts and decisions must still point at claims. An empty result
      // is the postcondition; anything else takes the open down NOW, while the
      // operator is looking at a migration, not weeks later as a claim whose
      // receipt silently vanished.
      for (const child of ['claim_source', 'claim_decision']) {
        const broken = db.prepare(`PRAGMA foreign_key_check(${child})`).all();
        if (broken.length > 0) {
          throw new Error(`claim rebuild broke ${broken.length} reference(s) from ${child}`);
        }
      }
    }
}

export function openDb(dbPath = DEFAULT_DB_PATH) {
  if (dbPath === ':memory:') {
    const db = new DatabaseSync(dbPath);
    hardenConnection(db);
    db.exec(SCHEMA);
    ensurePeopleProjectionSchema(db);
    migrate(db);
    return db;
  }

  // process.umask is process-global, but every operation in this section is
  // synchronous. Restore it in finally so callers and tests keep their own
  // policy even if SQLite creation or schema setup fails.
  const previousUmask = process.umask(0o077);
  let db;
  try {
    const dbDir = dirname(dbPath);
    mkdirSync(dbDir, { recursive: true, mode: 0o700 });
    const dbDirMode = statSync(dbDir).mode & 0o777;
    if (dbDirMode !== 0o700) {
      // Never chmod an arbitrary HERMES_DB parent: a path such as /tmp/db
      // must fail closed, not accidentally turn /tmp private for the process.
      throw new Error(
        `Hermes database directory must have mode 0700: ${dbDir} is ${dbDirMode.toString(8)}`
      );
    }
    if (existsSync(dbPath)) {
      if (!statSync(dbPath).isFile()) {
        throw new Error(`Hermes database path is not a regular file: ${dbPath}`);
      }
      chmodSync(dbPath, 0o600);
    }
    db = new DatabaseSync(dbPath);
    chmodSync(dbPath, 0o600);
    hardenConnection(db);
    db.exec(SCHEMA);
    ensurePeopleProjectionSchema(db);
    migrate(db);
    // Reassert after schema creation in case the platform replaced the file.
    chmodSync(dbPath, 0o600);
    return db;
  } catch (error) {
    try {
      db?.close();
    } catch {}
    throw error;
  } finally {
    process.umask(previousUmask);
  }
}

// --- canonical content hash --------------------------------------------------
