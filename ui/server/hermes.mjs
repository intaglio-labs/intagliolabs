// Extracted to ./contentHash.mjs and re-exported here (L5 step 6, public
// lookup): ui/server/relationship/lookup.mjs writes its own source='web'
// context rows and needs the SAME hash this file computes for every other
// row, rather than forking a second implementation that could disagree on
// serialization. See contentHash.mjs for the full canonicalization contract.
export { canonicalHash };

// Validates everything before writing anything, so a bad row midway through a
// batch rejects the whole batch instead of leaving half of it behind — the
// ingestion pipeline retries whole batches, not offsets.
//
// Rows MAY carry an entity_id (stable logical identity, formats in
// ops/INGESTION.md). Those rows upsert: absent → insert; present with an equal
// content_hash → unchanged (redelivery is free); present with a different hash
// → update in place, latest wins. Rows without entity_id always insert.
// Returns {inserted, updated, unchanged}.
// --- derived-memory cleanup --------------------------------------------------
//
// Every path that removes or rewrites a context row comes through here. It is
// code rather than ON DELETE CASCADE on purpose: a cascade fires the AFTER
// DELETE trigger that tombstones claim_fts only when recursive_triggers is on,
// and nothing in this file turns it on. Relying on the cascade would leave the
// claim text legible in the FTS index after the row it came from was deleted --
// the exact failure the whole deletion story exists to prevent.
//
// Order is decision -> source -> claim, and claim last is what makes the
// tombstone happen: claim_ad fires on the DELETE from claim, once the rows
// pointing at it are already gone.
const CLAIM_ID_CHUNK = 400;

function chunk(list, size = CLAIM_ID_CHUNK) {
  const out = [];
  for (let i = 0; i < list.length; i += size) out.push(list.slice(i, i + size));
  return out;
}

// Claims are deleted, never marked. Privacy deletion outranks historical
// audit -- see the trigger comment in SCHEMA for why no BEFORE DELETE guard
// stands in the way.
function deleteClaimsByIds(db, claimIds) {
  if (claimIds.length === 0) return 0;
  let deleted = 0;
  for (const part of chunk(claimIds)) {
    const marks = part.map(() => '?').join(',');
    db.prepare(`DELETE FROM claim_decision WHERE claim_id IN (${marks})`).run(...part);
    db.prepare(`DELETE FROM claim_source WHERE claim_id IN (${marks})`).run(...part);
    deleted += Number(db.prepare(`DELETE FROM claim WHERE id IN (${marks})`).run(...part).changes);
  }
  return deleted;
}

// Every claim resting on any of these context rows, whatever its decision
// state. Used by the deletion paths, where the source is going away entirely.
function claimIdsForContextIds(db, contextIds) {
  if (contextIds.length === 0) return [];
  const ids = new Set();
  for (const part of chunk(contextIds)) {
    const marks = part.map(() => '?').join(',');
    for (const r of db
      .prepare(`SELECT DISTINCT claim_id FROM claim_source WHERE context_id IN (${marks})`)
      .all(...part)) {
      ids.add(Number(r.claim_id));
    }
  }
  return [...ids];
}

// The upsert case, which is narrower: only claims whose SNAPSHOT no longer
// describes the row are invalidated. A claim taken from text that survived the
// upsert unchanged is still a true receipt and stays. The row is left eligible
// for redistillation by its bumped store_changed_at, not by anything here.
function invalidateClaimsForChangedRow(db, contextId, currentHash) {
  const stale = db
    .prepare('SELECT claim_id FROM claim_source WHERE context_id = ? AND content_hash IS NOT ?')
    .all(contextId, currentHash)
    .map((r) => Number(r.claim_id));
  return deleteClaimsByIds(db, stale);
}

// Everything derived from the context rows a predicate selects, deleted in the
// caller's transaction and BEFORE the context rows themselves -- claim_source
// holds a real REFERENCES to context(id), and foreign_keys is on now.
//
// Also harvests the rows' content hashes, because the distill cache keys on
// them and the caller owes those files an unlink: a cached model answer about
// a purged row is residue exactly like a claim about it.
function deleteClaimsForContextWhere(db, whereSql, params) {
  const rows = db.prepare(`SELECT id, content_hash FROM context WHERE ${whereSql}`).all(...params);
  const contextIds = rows.map((r) => Number(r.id));
  const contentHashes = rows.map((r) => r.content_hash).filter((h) => typeof h === 'string');
  return {
    claimsDeleted: deleteClaimsByIds(db, claimIdsForContextIds(db, contextIds)),
    contentHashes,
  };
}

// The cursor's next value, and it is STRICTLY MONOTONIC rather than a bare
// Date.now(). This is not fussiness about clocks; a wall-clock cursor is
// unsafe for a table that updates rows in place, and the failure is silent.
//
// Distillation resumes on (store_changed_at, id) > (last_changed_at, last_id).
// With bare millisecond stamps, suppose a run ends with its cursor at
// (T, id=7). A row with id=3 is then edited inside that same millisecond and
// stamped T. On the next run (T, 3) is NOT greater than (T, 7), so the edit is
// skipped -- forever, because nothing will ever move that row's cursor value
// again unless it is edited a second time. The claim derived from the OLD text
// was already invalidated by the upsert, so the net effect is a row that
// silently loses its memory and never gets it back.
//
// max(now, highest + 1) makes every write strictly greater than every write
// before it, which is the property the resumption key actually needs. Under a
// burst it runs slightly ahead of the wall clock and settles back the moment
// the writer goes idle; it is a sequence that happens to be readable as a
// time, not a clock reading.
function nextStoreChangedAt(db) {
  const highest = Number(db.prepare('SELECT MAX(store_changed_at) AS m FROM context').get()?.m ?? 0);
  return Math.max(Date.now(), highest + 1);
}

// The complete set of fields a caller may put on an ingest row. Anything else
// is a typo or a misunderstanding, and both are better as a 400 than as a
// silently different write. Kept beside insertRows rather than with the admin
// field sets because this one is the connector-facing contract.
const INGEST_ROW_FIELDS = Object.freeze(['ts', 'source', 'speaker', 'text', 'meta', 'entity_id']);

export function insertRows(db, rows) {
  const list = Array.isArray(rows) ? rows : [rows];
  const counts = { inserted: 0, updated: 0, unchanged: 0 };
  if (list.length === 0) return counts;
  const clean = list.map((row, i) => {
    if (row === null || typeof row !== 'object' || Array.isArray(row)) {
      throw badRow(i, 'not an object');
    }
    // A CLOSED FIELD SET, like every /admin/* route already had.
    //
    // /ingest was the only write path that silently ignored what it did not
    // recognise, and the failure that buys is specific: a connector sending
    // `entityId` instead of `entity_id` has its key dropped, so every delivery
    // takes the plain-insert branch and the store grows a duplicate of the
    // same record on every poll — with no error, and counts that read as
    // healthy because `inserted` is exactly what an insert reports.
    for (const key of Object.keys(row)) {
      if (!INGEST_ROW_FIELDS.includes(key)) {
        throw badRow(
          i,
          `unknown field ${JSON.stringify(key)}; allowed: ${INGEST_ROW_FIELDS.join(', ')}`
        );
      }
    }
    if (typeof row.source !== 'string' || row.source.length === 0) {
      throw badRow(i, 'missing "source" string');
    }
    // WRITABLE AND DELETABLE ARE NOW THE SAME PREDICATE.
    //
    // Until 2026-08-22 this accepted any non-empty string while every
    // /admin/* route rejected anything outside KNOWN_SOURCES. A row written
    // under an unlisted source was therefore one hermes could never delete —
    // and the comment above KNOWN_SOURCES records that happening for real, to
    // `files` and `notion`, where the only way to remove their data was a path
    // that did not exist.
    //
    // The two halves disagreeing is the bug. A closed set enforced on the way
    // out but not on the way in does not bound what is in the store; it only
    // bounds what can leave it.
    if (!KNOWN_SOURCES.includes(row.source)) {
      throw badRow(
        i,
        `unknown source ${JSON.stringify(row.source)} — a row hermes cannot delete. ` +
          `Valid sources: ${KNOWN_SOURCES.join(', ')}`
      );
    }
    if (typeof row.text !== 'string' || row.text.length === 0) {
      throw badRow(i, 'missing "text" string');
    }
    if (row.ts !== undefined && !Number.isFinite(row.ts)) {
      throw badRow(i, '"ts" must be epoch milliseconds');
    }
    if (row.speaker !== undefined && row.speaker !== null && typeof row.speaker !== 'string') {
      throw badRow(i, '"speaker" must be a string');
    }
    if (
      row.entity_id !== undefined &&
      row.entity_id !== null &&
      (typeof row.entity_id !== 'string' || row.entity_id.length === 0)
    ) {
      throw badRow(i, '"entity_id" must be a non-empty string');
    }
    // A KEYED ROW MUST CARRY ITS OWN ts.
    //
    // `ts` defaults to Date.now(), and `ts` is folded into the content hash.
    // For a one-shot row that is harmless. For an ENTITY row — one redelivered
    // on every poll under a stable entity_id — it is not: each delivery
    // defaults to a different `now`, so the hash differs, so the upsert reads
    // as an edit, so invalidateClaimsForChangedRow fires and deletes the
    // owner's ACCEPTED claims for that row along with their decision history.
    // Every poll, silently, for a row nobody edited.
    //
    // connectors/AGENTS.md already tells connectors to "always send ts on
    // entity rows (a server-defaulted ts changes the content hash every
    // delivery)". That was a rule connector authors had to remember. It is now
    // a refusal, because the cost of forgetting it is destroyed owner decisions
    // and the symptom is silence.
    if (row.entity_id !== undefined && row.entity_id !== null && row.ts === undefined) {
      throw badRow(
        i,
        'a row with "entity_id" must carry "ts" — a server-defaulted ts re-hashes on ' +
          'every delivery and would delete this row\'s accepted claims'
      );
    }
    const meta = row.meta === undefined || row.meta === null ? null : row.meta;
    const normalized = {
      ts: row.ts !== undefined ? Math.trunc(row.ts) : Date.now(),
      source: row.source,
      speaker: row.speaker ?? null,
      text: row.text,
      metaJson: meta === null ? null : JSON.stringify(meta),
      entityId: row.entity_id ?? null,
    };
    normalized.contentHash = canonicalHash({
      ts: normalized.ts,
      speaker: normalized.speaker,
      text: normalized.text,
      meta,
    });
    return normalized;
  });
  const ins = db.prepare(
    'INSERT INTO context(ts, source, speaker, text, meta, entity_id, content_hash, store_changed_at) ' +
      'VALUES (?, ?, ?, ?, ?, ?, ?, ?)'
  );
  // MATCHED ON (source, entity_id), NOT entity_id ALONE.
  //
  // Entity ids are only unique WITHIN a source — connectors/AGENTS.md defines
  // them per connector, and shapes like `health:<metric>:<YYYY-MM-DD>` or a
  // bare row id collide across sources easily. Matching on the id alone meant
  // one connector could silently overwrite another connector's row in place:
  // the text is replaced, invalidateClaimsForChangedRow fires, and the
  // owner's accepted claims on the victim row are destroyed. It also made the
  // row undeletable by its real owner, since /admin/delete-entities keys on
  // (source, entity_id).
  //
  // That delete route already required BOTH, with a comment saying it does so
  // "so a connector with a crossed-up id list cannot delete another source's
  // rows". The guard was on the harmless side and missing from the
  // destructive one.
  const sel = db.prepare('SELECT id, content_hash FROM context WHERE source = ? AND entity_id = ?');
  const upd = db.prepare(
    'UPDATE context SET ts = ?, speaker = ?, text = ?, meta = ?, content_hash = ?, store_changed_at = ? ' +
      'WHERE source = ? AND entity_id = ?'
  );
  // SELECT-then-write rather than ON CONFLICT DO UPDATE: the route contract
  // reports inserted/updated/unchanged separately, and ON CONFLICT cannot say
  // which branch ran without a second query anyway. Safe from races because
  // the whole batch runs in one transaction on the database's only writer.
  // The FTS index needs no attention here — the context_au trigger mirrors an
  // UPDATE's text into it exactly as context_ai mirrors an INSERT's.
  //
  // store_changed_at is set HERE and only here, on the two branches that
  // actually change the stored row. An unchanged redelivery must not bump it:
  // the cursor means "when Hermes last changed this row", and a connector
  // re-shipping the same rows hourly would otherwise drag the whole corpus
  // forward and re-propose every claim in it.
  db.exec('BEGIN');
  try {
    // One value for the whole batch, computed inside the transaction. Rows
    // that change together share a cursor position, which is correct: a run
    // that reads any of them reads all of them.
    const changedAt = nextStoreChangedAt(db);
    // Old content hashes whose cached distillates die with this batch. The
    // unlinks run BEFORE COMMIT, here and in every admin deletion route, and
    // the ordering is a deliberate choice of failure mode: the filesystem has
    // no transaction to join, so one side must bear the crash window. After
    // COMMIT, dying in between leaves the deleted text's derivative on disk
    // forever; before, a rollback merely re-spends one distillation. Privacy
    // residue vs wasted compute -- we pay compute.
    const staleCache = [];
    for (const r of clean) {
      if (r.entityId !== null) {
        const existing = sel.get(r.source, r.entityId);
        if (existing !== undefined) {
          if (existing.content_hash === r.contentHash) {
            counts.unchanged += 1;
          } else {
            upd.run(r.ts, r.speaker, r.text, r.metaJson, r.contentHash, changedAt, r.source, r.entityId);
            // In THIS transaction, not a follow-up sweep. Between the two the
            // database would hold a claim quoting text the row no longer says,
            // and the review page would show a receipt that does not match.
            //
            // Deliberately NOT reported in the return value: {inserted,
            // updated, unchanged} is the connector-facing contract, and
            // connectors sit outside the memory boundary. A connector has no
            // business learning how many conclusions the owner's corpus
            // carried, and widening a response shape that callers already
            // parse is how a contract quietly becomes four fields.
            invalidateClaimsForChangedRow(db, Number(existing.id), r.contentHash);
            if (typeof existing.content_hash === 'string') staleCache.push(existing.content_hash);
            counts.updated += 1;
          }
          continue;
        }
      }
      ins.run(r.ts, r.source, r.speaker, r.text, r.metaJson, r.entityId, r.contentHash, changedAt);
      counts.inserted += 1;
    }
    // Best-effort (strict: false), unlike the admin deletion routes. A route
    // that answered "deleted" must not have left a quote on disk, so there a
    // failed unlink throws and the transaction rolls back. Here the failure
    // mode inverts: throwing would refuse NEW rows over residue of a row the
    // store still holds, turning one damaged cache directory into a 500 on
    // every batch carrying a content-changed redelivery — retried by the
    // connector forever. The cache logs the residue once per process, and the
    // next strict deletion route over the same hash surfaces it.
    dropCachedDistillates(staleCache, undefined, { strict: false });
    db.exec('COMMIT');
  } catch (e) {
    db.exec('ROLLBACK');
    throw e;
  }
  return counts;
}

function badRow(i, why) {
  return Object.assign(new Error(`ingest[${i}]: ${why}`), { status: 400 });
}

// --- corpus query helpers: NO CALLER UNTIL THE SEALED READER EXISTS ---------
//
// GET /search and GET /recent were deleted (see the route table in handle()).
// These two functions are what those routes were made of, and they are kept
// deliberately rather than deleted with them: ftsQuery encodes FTS5 injection
// hardening that took a real bug to find, and re-deriving it from scratch in
// a separate module is how that hardening gets quietly lost. They are
// exported so their absence of an HTTP caller cannot be mistaken for dead code
// to tidy away, and so the vault can import rather than copy them.
//
// Nothing here may be reattached to an HTTP route. The sealed reader calls them
// in-process, composes an answer, and returns speech -- never rows.

// FTS5 treats bare input as its own query language, so raw user text like
// `who's there?` or an unbalanced quote is a syntax error. Quoting every term
// makes each one a plain string. Terms are joined with OR, not FTS5's default
// AND: the caller is the voice loop passing a whole utterance, and requiring
// every word of an utterance to appear in one row would match almost nothing.
// bm25 rank still puts rows matching more (and rarer) terms first.
export function ftsQuery(q) {
  const terms = q.split(/\s+/).filter(Boolean);
  if (terms.length === 0) return null;
  return terms.map((t) => `"${t.replaceAll('"', '""')}"`).join(' OR ');
}

export function clampLimit(raw, fallback = 8, max = 50) {
  const n = Number.parseInt(raw ?? '', 10);
  if (!Number.isFinite(n) || n < 1) return fallback;
  return Math.min(n, max);
}

