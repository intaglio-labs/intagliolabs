// Hermes — the runtime that will own state, memory, permissions, and policy.
//
// The first seed of it minted OpenAI client secrets, because the key was the
// one thing the client could never hold. That pipeline is gone: the voice
// stack is local now and there is no key. What remains is the other half of
// Hermes' charter — state. Today it is the context store: a SQLite database
// of ingested household context (transcripts, notes, whatever the ingestion
// pipeline hands it) that the voice loop queries before answering. The DB
// lives in Hermes-owned private runtime storage, not in the page or checkout:
// the page is an embodiment that forgets on reload; this process does not.
//
// Run it from ui/:  npm run hermes        (node server/hermes.mjs)
// The app expects it at http://localhost:51789 (override: EXPO_PUBLIC_HERMES_URL
// client-side, HERMES_PORT here). Context defaults to the private path
// ~/.hazlie/context/context.db; HERMES_DB moves it. HERMES_ALLOWED_ORIGINS is a
// comma-separated exact CORS allowlist (default: EMPTY -- no browser origin is
// trusted unless one is named; the bearer channel is how every caller arrives).
// HERMES_TOKEN_FILE moves the bearer token (default
// ~/.hazlie/secrets/hermes-token.txt, generated by ops/setup-llm.sh).
//
// THE CORPUS DOES NOT LEAVE THIS PROCESS. No route returns a context row to
// a browser or to the courier; exactly one bearer-only review route
// (GET /admin/memory/pending) returns a quote, to the owner, about their own
// corpus (ui/AGENTS.md, amended 2026-08-22). /search and /recent existed and
// were deleted: they were the least-guarded routes on the server, and any row
// they returned landed in a browser bundle that also talks to models.
// Retrieval becomes an in-process call owned by the sealed reader
// (handleVaultAsk, below); when it landed it composes an answer and returns
// speech, never rows. A future `send(res, 200, { results })` here undoes the
// whole boundary in one line.
//
// Every route except /health requires an authorized caller -- see authorize()
// for the two channels and for the residual gap it does not close. The
// /admin/* lifecycle routes (retention, purge, reconciliation, maintenance)
// go further and accept only the bearer channel: Hermes is the corpus's sole
// writer AND sole deleter, and deletion is not a browser capability.
//
// Zero dependencies on purpose. Node's built-ins cover the context routes and
// bounded streaming proxy; this process is the seed of a policy runtime, not a
// web framework showcase.

