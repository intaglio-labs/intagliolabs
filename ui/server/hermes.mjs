      const body = await readJson(req);
      assertClosedFields(body, PURGE_FIELDS);
      assertKnownSource(body.source);
      clearPeopleSearchCacheStorage(policy.peopleSearchCache, policy.peopleSearchCachePath);
      let deleted = 0;
      let claimsDeleted = 0;
      db.exec('BEGIN');
      try {
        // Before the rows, not after: claim_source REFERENCES context(id) and
        // foreign_keys is on, so the other order is a constraint failure --
        // which is the design working, but a 500 is not the answer a purge
        // should give.
        const swept = deleteClaimsForContextWhere(db, 'source = ?', [body.source]);
        claimsDeleted = swept.claimsDeleted;
        dropCachedDistillates(swept.contentHashes);
        deleted = Number(db.prepare('DELETE FROM context WHERE source = ?').run(body.source).changes);
        if (isProjectedPeopleSource(body.source)) clearPeopleProjection(db);
        db.exec('COMMIT');
      } catch (e) {
        db.exec('ROLLBACK');
        throw e;
      }
      // Inline and immediate, never deferred to the maintenance window: a
      // purge means "this source's data must be gone", and until the FTS
      // rebuild and VACUUM run, the deleted text is still legible in the
