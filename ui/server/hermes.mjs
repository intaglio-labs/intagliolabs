// The FTS index is a shadow of context.text, kept in sync by triggers rather
// than by application code, so rows written by ANY path — /ingest, the seed
// script's direct-DB fallback, sqlite3 at a prompt — are searchable.
//
// `speaker` is caller-supplied TEXT attribution from the ingestion pipeline —
// a label that arrives alongside the text, like `source`. Nothing in this
// codebase may ever derive it from audio: no voiceprints, no enrollment, no
// cross-session identification of a voice. The ear's identity surface stays
// ephemeral per session (project policy — the BIPA line in README).
//
// `entity_id` is a connector-supplied stable logical identity (the registry of
// formats lives in ops/INGESTION.md) that turns redelivery into an upsert
// instead of a duplicate row; `content_hash` is the server-computed canonical
// hash that decides whether an upsert is a real change. The partial UNIQUE
// index over entity_id is created in migrate() rather than here — see the
// why-comment there before "fixing" that.
