const APPLY_CLAIM_FIELDS = Object.freeze(['kind', 'text', 'p_claim', 'source']);
const DECIDE_FIELDS = Object.freeze(['claim_id', 'action', 'reason']);
const PENDING_PARAMS = Object.freeze(['limit']);
const RECALL_PARAMS = Object.freeze(['q', 'limit']);
const DECISION_ACTIONS = Object.freeze(['accept', 'reject', 'retract']);
// The review page is the v1 product surface and it has to show the receipt, so
// this cap is about one sitting's reading, not about safety.
const PENDING_CAP = 200;
// Row mode names the row; EPISODE mode names the LINE and hermes resolves the
// row itself. Both are listed so the closed-field check accepts either shape,
// and the staging code below refuses the combination -- see the note there.
const APPLY_SOURCE_FIELDS = Object.freeze(['context_id', 'line', 'quote', 'content_hash']);
const CLAIM_KINDS = Object.freeze(['fact', 'preference', 'constraint', 'plan', 'commitment']);
const APPLY_CLAIM_CAP = 500;

function assertClosedFields(body, allowed) {
  if (body === null || typeof body !== 'object' || Array.isArray(body)) {
    throw badRequest('body must be a JSON object');
  }
  for (const key of Object.keys(body)) {
    if (!allowed.includes(key)) {
      throw badRequest(
        `unknown field ${JSON.stringify(key)}; this route accepts: ${allowed.join(', ') || '(no fields)'}`
      );
    }
  }
}

// The physical cleanup that makes "deleted" mean deleted for the FTS index.
// FTS5's delete path writes only a tombstone: the row's text remains legible
// inside the index's own pages until a rebuild rewrites them, and the freed
// pages are only then zeroed by VACUUM under secure_delete. VACUUM blocks this
// single-threaded server for its whole duration — every /ingest and lane
// request queues behind it — so routine callers schedule /admin/maintain in an
// idle window; only /admin/purge pays for it inline (see the why there).
function maintainNow(db) {
  db.exec(`INSERT INTO context_fts(context_fts) VALUES('rebuild')`);
  // claim_fts holds model text quoting the corpus. A rebuild that skipped it
  // would leave a deleted claim's sentence legible in the index's own pages,
  // which is the same failure the context rebuild exists to prevent.
  db.exec(`INSERT INTO claim_fts(claim_fts) VALUES('rebuild')`);
  db.exec('VACUUM');
}

// /admin/entities exists for one purpose: window reconciliation. Upserts
// cannot express deletion, so after a window scan a connector fetches the ids
// Hermes holds for that window, diffs against what it observed, and deletes
// the difference. Above the cap the honest answer is "slice the window" — a
// silently truncated list would read to a reconciler as "these entities no
// longer exist", and it would then delete the remainder.
const ENTITY_WINDOW_CAP = 5000;

function parseTsParam(params, name, fallback) {
  const raw = params.get(name);
  if (raw === null || raw === '') return fallback;
  const n = Number(raw);
  if (!Number.isFinite(n)) throw badRequest(`"${name}" must be epoch milliseconds`);
  return Math.trunc(n);
}

// What the review page renders: claims with no decision yet, newest first,
// WITH their text and their quote.
//
// That is a deliberate exception to the rule that admin routes return ids and
// timestamps only, and it is worth being explicit about why it is safe here.
// The /admin/entities rule exists because that response goes to a CONNECTOR
// process, whose logs and state files sit outside the corpus boundary. This
// response goes to a loopback page the owner is reading, over the bearer
// channel, and a review page that hides the quote is not a review page — the
// whole product claim is that the owner sees exactly what the model saw.
//
// What must NOT happen is this text reaching Messages. `hz memory` returns
// counts only; quotes never transit Apple's servers to every device on the
// Apple ID. That boundary lives in the courier, not here.
// THE QUEUE IS NOT EVERYTHING PROPOSED, and that is the point.
//
// A claim the model itself is unsure about is not worth a person's attention up
// front. Below this floor a claim is not queued, not counted as waiting, and
// never nags — it simply sits, and it can still surface later at the point of
// use, when a real question has just matched it and the decision is worth making.
// Nothing is deleted and nothing is auto-accepted; the difference is only whether
// the owner is ASKED, and when.
//
// NULL is not low. A claim distilled before the prompt asked for a number carries
// no p, which is unknown rather than doubtful, so it stays in the queue.
export const REVIEW_FLOOR = 0.5;

export function pendingClaims(db, { limit = PENDING_CAP } = {}) {
  const rows = db
    .prepare(
      'SELECT c.id, c.kind, c.text, c.observed_at, c.p_claim, c.created_at, ' +
        's.context_id, s.source, s.quote, s.content_hash AS snapshot_hash, ' +
        'r.model, r.prompt_path, r.prompt_sha, ' +
        'x.ts AS source_ts, x.content_hash AS current_hash ' +
        'FROM claim c ' +
        'JOIN claim_source s ON s.claim_id = c.id ' +
        'JOIN distill_run r ON r.id = c.run_id ' +
        'LEFT JOIN context x ON x.id = s.context_id ' +
        'WHERE NOT EXISTS (SELECT 1 FROM claim_decision d WHERE d.claim_id = c.id) ' +
        // The floor — see REVIEW_FLOOR. Doubtful claims wait for a question
        // rather than for the owner.
        'AND (c.p_claim IS NULL OR c.p_claim >= ' + REVIEW_FLOOR + ') ' +
        // CONFIDENCE FIRST, then newest. The queue used to be c.id DESC alone,
        // which is arrival order -- fine at a hundred claims and useless at the
        // scale this corpus reaches, where the reader's attention runs out long
        // before the queue does. Ordering by the model's own p_claim front-loads
        // the claims most likely to be accepted and lets the doubtful tail sit
        // pending instead of demanding attention. That is the whole reason
        // prompt v2 asks for the number.
        //
        // NULLS LAST because an unranked claim is UNKNOWN, not low: rows
        // distilled before v2 carry NULL. They sink below ranked claims rather
        // than being lost, and they largely disappear on their own -- cacheKey()
        // includes promptSha, so the v2 prompt invalidates every cached answer
        // and a re-run assigns them a p.
        'ORDER BY c.p_claim DESC NULLS LAST, c.id DESC LIMIT ?'
    )
    .all(Math.min(limit, PENDING_CAP) + 1);
  const more = rows.length > Math.min(limit, PENDING_CAP);
  return { claims: more ? rows.slice(0, -1) : rows, more };
}

// Counts only -- this is what `hz memory` is allowed to send through Messages.
//
// `stale` should always be zero: a content-changing upsert deletes the claims
// whose snapshot it broke, in the same transaction. It is reported anyway,
// because a non-zero value means that invalidation path has a hole, and a
// number nobody computes is a hole nobody finds.
export function claimCounts(db) {
  const one = (sql, ...args) => Number(db.prepare(sql).get(...args).n);
  return {
    proposed: one(
      'SELECT count(*) AS n FROM claim c WHERE NOT EXISTS ' +
        '(SELECT 1 FROM claim_decision d WHERE d.claim_id = c.id)'
    ),
    // Of those, the ones actually being ASKED about. `proposed` is the honest
    // total and stays; `queued` is what the owner is on the hook for, and the
    // difference between them is the doubtful tail waiting for a question.
    queued: one(
      'SELECT count(*) AS n FROM claim c WHERE NOT EXISTS ' +
        '(SELECT 1 FROM claim_decision d WHERE d.claim_id = c.id) ' +
        'AND (c.p_claim IS NULL OR c.p_claim >= ?)',
      REVIEW_FLOOR
    ),
    accepted: one('SELECT count(*) AS n FROM v_claim_accepted'),
    rejected: one(
      "SELECT count(*) AS n FROM claim c WHERE (SELECT d.action FROM claim_decision d " +
        "WHERE d.claim_id = c.id ORDER BY d.created_at DESC, d.id DESC LIMIT 1) IN ('reject','retract')"
    ),
    stale: one(
      'SELECT count(*) AS n FROM claim_source s JOIN context x ON x.id = s.context_id ' +
        'WHERE s.content_hash IS NOT x.content_hash'
    ),
  };
}

// Append a decision. The claim is never touched -- claim_decision is the only
// table that moves, and it only ever grows. Changing your mind appends again.
export function decideClaim(db, body) {
  assertClosedFields(body, DECIDE_FIELDS);
  if (!Number.isInteger(body.claim_id)) throw badRequest('"claim_id" must be an integer');
  if (!DECISION_ACTIONS.includes(body.action)) {
    throw badRequest(`"action" must be one of: ${DECISION_ACTIONS.join(', ')}`);
  }
  if (body.reason !== undefined && body.reason !== null && typeof body.reason !== 'string') {
    throw badRequest('"reason" must be a string');
  }
  const exists = db.prepare('SELECT 1 AS ok FROM claim WHERE id = ?').get(body.claim_id);
  if (exists === undefined) throw badRequest(`no claim ${body.claim_id}`);
  db.prepare(
    'INSERT INTO claim_decision(claim_id, action, actor, reason, created_at) ' +
      "VALUES (?, ?, 'owner', ?, ?)"
  ).run(body.claim_id, body.action, body.reason ?? null, Date.now());
  return { claim_id: body.claim_id, action: body.action };
}

// Claims in a run that carry no receipt. Exported so the guard below and the
// test that pins it are demonstrably the same query rather than two that
// happen to agree today.
export function orphanClaimCount(db, runId) {
  return Number(
    db
      .prepare(
        'SELECT count(*) AS n FROM claim c WHERE c.run_id = ? ' +
          'AND NOT EXISTS (SELECT 1 FROM claim_source s WHERE s.claim_id = c.id)'
      )
      .get(runId).n
  );
}

// The trusted apply path: the ONE way a model's output becomes a row.
//
// Everything here runs server-side because the distiller is not trusted to
// police itself. It proposes; Hermes holds the corpus, so Hermes is the only
// party that can actually check a receipt:
//
//   * the quote must be an EXACT substring of the cited row's text right now.
//     Not "similar to", not "was at distill time" -- if the row changed under
//     the distiller, the receipt is stale and the claim does not land.
//   * the content_hash the distiller says it read must still be the row's
//     hash. This catches the same drift a beat earlier and names it precisely.
//   * observed_at is copied off the row, never taken from the caller.
//   * subject is 'owner', closed in the schema and not a field here at all.
//
// A claim that fails any of these is REJECTED BY INDEX rather than silently
// dropped: a distiller that gets a 200 and quietly loses half its output has
// no way to tell that from a corpus with nothing in it.
export function applyMemoryBatch(db, body) {
  assertClosedFields(body, APPLY_FIELDS);
  const run = body.run;
  assertClosedFields(run ?? null, APPLY_RUN_FIELDS);
  for (const key of ['model', 'prompt_path', 'prompt_sha']) {
    if (typeof run[key] !== 'string' || run[key].length === 0) {
      throw badRequest(`"run.${key}" must be a non-empty string`);
    }
  }
  if (run.params === undefined || run.params === null || typeof run.params !== 'object') {
    throw badRequest('"run.params" must be an object');
  }
  if (run.episode_hash !== undefined && run.episode_hash !== null) {
    if (typeof run.episode_hash !== 'string' || !/^[0-9a-f]{64}$/u.test(run.episode_hash)) {
      throw badRequest('"run.episode_hash" must be a sha256 hex digest');
    }
    // The episode has to exist, or `line` resolves against nothing and every
    // claim in the batch would be refused one by one with a confusing message.
    const known = db
      .prepare('SELECT 1 AS ok FROM episode WHERE member_hash = ? LIMIT 1')
      .get(run.episode_hash);
    if (known === undefined) throw badRequest('"run.episode_hash" names no known episode');
  }
  if (run.episode_context !== undefined && run.episode_context !== null) {
    if (run.episode_context !== 'off' && run.episode_context !== 'on') {
      throw badRequest('"run.episode_context" must be "off" or "on"');
    }
  }
  for (const key of ['from_changed_at', 'through_changed_at', 'rows_in', 'started_at', 'through_id']) {
    const v = run[key];
    if (v !== undefined && v !== null && !Number.isFinite(v)) {
      throw badRequest(`"run.${key}" must be a number`);
    }
  }
  const claims = body.claims;
  // AN EPISODE THAT YIELDED NOTHING IS A RESULT, and it has to be recordable.
  //
  // Row mode still requires at least one claim: a row is picked by a cursor
  // that moves regardless, so an empty batch there is a caller mistake. An
  // EPISODE is picked by "no complete run names this member_hash", so an
  // episode the model read and found nothing in must still record a run --
  // otherwise it is re-read on every pass, forever, and the pass never drains.
  // Most conversations contain no durable claim, so this is the common case,
  // not the edge one.
  const episodeRun = run?.episode_hash !== undefined && run?.episode_hash !== null;
  const floor = episodeRun ? 0 : 1;
  if (!Array.isArray(claims) || claims.length < floor || claims.length > APPLY_CLAIM_CAP) {
    throw badRequest(
      `"claims" must be an array of ${floor} to ${APPLY_CLAIM_CAP} objects`
    );
  }

  // Shape validation first, in full, before the transaction opens. A 400 must
  // never leave a half-written run row behind.
  const staged = claims.map((claim, i) => {
    const at = (why) => badRequest(`claims[${i}]: ${why}`);
    if (claim === null || typeof claim !== 'object' || Array.isArray(claim)) {
      throw at('not an object');
    }
    for (const key of Object.keys(claim)) {
      if (!APPLY_CLAIM_FIELDS.includes(key)) {
        throw at(`unknown field ${JSON.stringify(key)}; accepts: ${APPLY_CLAIM_FIELDS.join(', ')}`);
      }
    }
    if (!CLAIM_KINDS.includes(claim.kind)) {
      throw at(`"kind" must be one of: ${CLAIM_KINDS.join(', ')}`);
    }
    if (typeof claim.text !== 'string' || claim.text.trim().length === 0) {
      throw at('"text" must be a non-empty string');
    }
    if (
      claim.p_claim !== undefined &&
      claim.p_claim !== null &&
      (!Number.isFinite(claim.p_claim) || claim.p_claim < 0 || claim.p_claim > 1)
    ) {
      throw at('"p_claim" must be a number between 0 and 1, or null');
    }
    const src = claim.source;
    if (src === null || typeof src !== 'object' || Array.isArray(src)) {
      throw at('"source" must be an object; v1 records exactly one source per claim');
    }
    for (const key of Object.keys(src)) {
      if (!APPLY_SOURCE_FIELDS.includes(key)) {
        throw at(`source: unknown field ${JSON.stringify(key)}`);
      }
    }
    // WHICH ROW A CLAIM RESTS ON IS THE SERVER'S DECISION IN EPISODE MODE.
    //
    // The distiller returns the LINE it quoted, not a row id, and hermes maps
    // that line to a context_id through episode_member. The mapping is the
    // whole security boundary: an episode deliberately shows the model text the
    // owner did not write, and `quotable` is what separates "may inform" from
    // "may be cited". If a caller could supply the row id directly it could
    // pair a received row's id with an owner row's quote -- the quote check
    // would pass, because the quote really is a span of the row it names, and
    // the claim would carry a receipt pointing at somebody else's words.
    //
    // So the two shapes are exclusive, and supplying both is refused rather
    // than resolved in some precedence order that a later reader has to know.
    const episodeMode = run.episode_hash !== undefined && run.episode_hash !== null;
    if (episodeMode) {
      if (src.context_id !== undefined) {
        throw at('source.context_id is not accepted in episode mode; send source.line');
      }
      if (!Number.isInteger(src.line) || src.line < 1) {
        throw at('"source.line" must be a positive integer');
      }
      const member = db
        .prepare(
          'SELECT m.context_id, m.quotable FROM episode_member m ' +
            'JOIN episode e ON e.id = m.episode_id ' +
            'WHERE e.member_hash = ? AND m.line_no = ?'
        )
        .get(run.episode_hash, src.line);
      if (member === undefined) throw at(`source.line ${src.line} is not in this episode`);
      if (member.quotable !== 1) {
        // The distiller checks this too. It is checked again here because the
        // distiller is a client, and a client is not a boundary.
        throw at(`source.line ${src.line} is not a line the owner wrote`);
      }
      src.context_id = Number(member.context_id);
    } else if (src.line !== undefined) {
      throw at('source.line is only accepted for an episode run');
    }
    if (!Number.isInteger(src.context_id)) throw at('"source.context_id" must be an integer');
    if (typeof src.quote !== 'string' || src.quote.length === 0) {
      throw at('"source.quote" must be a non-empty string');
    }
    if (
      src.content_hash !== undefined &&
      src.content_hash !== null &&
      typeof src.content_hash !== 'string'
    ) {
      throw at('"source.content_hash" must be a string');
    }
    return { i, claim, src };
  });

  const now = Date.now();
  const getRow = db.prepare(
    'SELECT id, ts, source, entity_id, content_hash, text FROM context WHERE id = ?'
  );
  const insRun = db.prepare(
    'INSERT INTO distill_run(model, prompt_path, prompt_sha, params, from_changed_at, ' +
      'through_changed_at, through_id, episode_hash, episode_context, rows_in, claims_out, ' +
      'status, started_at, ended_at) ' +
      "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, 'complete', ?, ?)"
  );
  const insClaim = db.prepare(
    'INSERT INTO claim(run_id, subject, kind, text, observed_at, valid_to, p_claim, created_at) ' +
      "VALUES (?, 'owner', ?, ?, ?, ?, ?, ?)"
  );
  const insSource = db.prepare(
    'INSERT INTO claim_source(claim_id, context_id, source, entity_id, content_hash, quote) ' +
      'VALUES (?, ?, ?, ?, ?, ?)'
  );

  const rejected = [];
  let runId = null;
  let applied = 0;
  db.exec('BEGIN');
  try {
    runId = Number(
      insRun.run(
        run.model,
        run.prompt_path,
        run.prompt_sha,
        JSON.stringify(run.params),
        run.from_changed_at ?? null,
        run.through_changed_at ?? null,
        // The tie-breaker half of the cursor. Null only from a caller that
        // predates schema v7; the reader treats null as 0 and re-offers the
        // group rather than stepping over it.
        run.through_id ?? null,
        run.episode_hash ?? null,
        run.episode_context ?? null,
        Math.trunc(run.rows_in ?? 0),
        0,
        Math.trunc(run.started_at ?? now),
        now
      ).lastInsertRowid
    );
    for (const { i, claim, src } of staged) {
      const row = getRow.get(src.context_id);
      if (row === undefined) {
        rejected.push({ index: i, reason: 'no such context row' });
        continue;
      }
      if (!String(row.text).includes(src.quote)) {
        rejected.push({ index: i, reason: 'quote is not an exact substring of the cited row' });
        continue;
      }
      if (
        src.content_hash !== undefined &&
        src.content_hash !== null &&
        src.content_hash !== row.content_hash
      ) {
        rejected.push({ index: i, reason: 'cited row changed since it was read' });
        continue;
      }
      const claimId = Number(
        insClaim.run(
          runId,
          claim.kind,
          claim.text,
          // World time from the row, not the model. NULL stays NULL rather
          // than becoming "now" -- an unknown observation time is a fact
          // about the corpus, and inventing one makes it unfalsifiable.
          row.ts ?? null,
          // The day the claim is ABOUT, computed here for the same reason
          // observed_at is: it is a fact about the calendar, and a model-supplied
          // expiry would let a claim decide its own standing. NULL for anything
          // that is not a dated intention -- see memory/validity.mjs.
          validToFor(claim, { observedAt: row.ts ?? null }),
          claim.p_claim ?? null,
          now
        ).lastInsertRowid
      );
      insSource.run(
        claimId,
        Number(row.id),
        String(row.source),
        row.entity_id ?? null,
        row.content_hash ?? null,
        src.quote
      );
      applied += 1;
    }

    // THE POSTCONDITION. SQLite cannot express "a child row will arrive later
    // in this transaction", so the old plan's deferred trigger was never going
    // to work; this is the check that actually runs, and it runs while the
    // rollback is still available. A claim with no receipt is worse than no
    // claim: it is an assertion the review page cannot show the owner a reason
    // for, and it would sit in the store looking exactly like a real one.
    const orphans = orphanClaimCount(db, runId);
    if (orphans > 0) {
      throw Object.assign(
        new Error(`refusing to commit ${orphans} claim(s) with no source; batch rolled back`),
        { status: 500 }
      );
    }
    db.prepare('UPDATE distill_run SET claims_out = ? WHERE id = ?').run(applied, runId);
    db.exec('COMMIT');
  } catch (e) {
    db.exec('ROLLBACK');
    throw e;
  }
  return { run_id: runId, applied, rejected };
}

async function handleAdmin(db, req, res, cors, url, channel) {
  if (channel !== 'bearer') {
    // 403, not 401: the caller IS authenticated (allowlisted Origin) — it is
    // the channel that lacks the capability. The browser channel's Origin gate
    // is forgeable by a same-machine process under another uid (the residual
    // gap authorize() documents), and a page has no business deleting corpus;
    // saying so plainly beats sending a stale page off to re-check its token.
    send(
      res,
      403,
      {
        error:
          'admin routes are bearer-only: deletion is not a browser capability. ' +
          'Call with the token from ~/.hazlie/secrets/hermes-token.txt and no Origin header.',
      },
      cors
    );
    return;
  }

  if (req.method === 'GET' && url.pathname === '/admin/memory/pending') {
    for (const key of url.searchParams.keys()) {
      if (!PENDING_PARAMS.includes(key)) {
        throw badRequest(`unknown query parameter ${JSON.stringify(key)}`);
      }
    }
    const raw = url.searchParams.get('limit');
    const limit = raw === null || raw === '' ? PENDING_CAP : Number(raw);
    if (!Number.isInteger(limit) || limit < 1) throw badRequest('"limit" must be a positive integer');
    send(res, 200, { ...pendingClaims(db, { limit }), counts: claimCounts(db) }, cors);
    return;
  }

  // Feeds `hz ask`, whose answer goes out through Messages. The response
  // carries claim text, kind, source label and date -- and NO quote, because
  // recallClaims does not select one. That is the boundary: the owner's
  // verbatim words never transit Apple's servers, and the guarantee lives in
  // the SQL rather than in the courier remembering to strip a field.
  // WHAT WOULD HAVE ANSWERED THIS, HAD ANYONE CONFIRMED IT.
  //
  // The review queue asks about everything up front, which is a chore nobody
  // finishes; this is the other door. Given a question that found nothing
  // accepted, it returns the PROPOSED claim that would have answered it — one
  // decision, at the moment it pays off, with the question still on screen.
  //
  // Read-only and decides nothing. It also skips anything already decided, so a
  // rejected claim is never raised again.
  if (req.method === 'GET' && url.pathname === '/admin/memory/suggest') {
    for (const key of url.searchParams.keys()) {
      if (!RECALL_PARAMS.includes(key)) {
        throw badRequest(`unknown query parameter ${JSON.stringify(key)}`);
      }
    }
    const q = url.searchParams.get('q') ?? '';
    // Same hardening as recall: raw user text must never reach MATCH.
    const match = q.trim().length === 0 ? null : ftsQuery(q);
    send(
      res,
      200,
      { claims: pendingForQuery(db, { match, question: q, limit: clampLimit(url.searchParams.get('limit'), 1, 5) }) },
      cors
    );
    return;
  }

  if (req.method === 'GET' && url.pathname === '/admin/memory/recall') {
    for (const key of url.searchParams.keys()) {
      if (!RECALL_PARAMS.includes(key)) {
        throw badRequest(`unknown query parameter ${JSON.stringify(key)}`);
      }
    }
    const q = url.searchParams.get('q') ?? '';
    // ftsQuery is the injection hardening that took a real bug to find. Raw
    // user text must never reach MATCH.
    const match = q.trim().length === 0 ? null : ftsQuery(q);
    send(
      res,
      200,
      recallClaims(db, { match, limit: clampLimit(url.searchParams.get('limit'), 8, 25) }),
      cors
    );
    return;
  }

  if (req.method === 'GET' && url.pathname === '/admin/memory/counts') {
    send(res, 200, claimCounts(db), cors);
    return;
  }

  if (req.method === 'GET' && url.pathname === '/admin/entities') {
    for (const key of url.searchParams.keys()) {
      if (!ENTITIES_PARAMS.includes(key)) {
        throw badRequest(
          `unknown query parameter ${JSON.stringify(key)}; this route accepts: ${ENTITIES_PARAMS.join(', ')}`
        );
      }
    }
    const source = url.searchParams.get('source');
    assertKnownSource(source);
    const fromTs = parseTsParam(url.searchParams, 'from_ts', Number.MIN_SAFE_INTEGER);
    const toTs = parseTsParam(url.searchParams, 'to_ts', Number.MAX_SAFE_INTEGER);
    const rows = db
      .prepare(
        'SELECT entity_id, ts FROM context ' +
          'WHERE source = ? AND entity_id IS NOT NULL AND ts >= ? AND ts <= ? ' +
          'ORDER BY ts, entity_id LIMIT ?'
      )
      .all(source, fromTs, toTs, ENTITY_WINDOW_CAP + 1);
    if (rows.length > ENTITY_WINDOW_CAP) {
      throw Object.assign(
        new Error(
          `window holds more than ${ENTITY_WINDOW_CAP} entities; narrow from_ts/to_ts and reconcile in slices`
        ),
        { status: 413 }
      );
    }
    // Mapped field by field, never spread: ids and timestamps ONLY. A widened
    // SELECT must not be able to silently widen the response — text or meta
    // crossing back here would hand corpus content to the connector process,
    // whose logs and state files are outside the corpus boundary.
    send(
      res,
      200,
      { entities: rows.map((r) => ({ entity_id: r.entity_id, ts: Number(r.ts) })) },
      cors
    );
    return;
  }

  if (req.method === 'POST') {
    if (!hasJsonMediaType(req)) {
      send(res, 415, { error: 'content-type must be application/json' }, cors);
      return;
    }

    if (url.pathname === '/admin/retain') {
      const body = await readJson(req);
      assertClosedFields(body, RETAIN_FIELDS);
      assertKnownSource(body.source);
      const keepDays = body.keep_days;
      if (!Number.isInteger(keepDays) || keepDays < 1 || keepDays > 3650) {
        throw badRequest('"keep_days" must be an integer between 1 and 3650');
      }
      // Routine retention deletes cheaply and leaves the physical cleanup to a
      // scheduled /admin/maintain; only an explicit purge pays for it inline.
      //
      // One cutoff, computed once: calling Date.now() in both statements would
      // let a claim survive whose row was deleted a millisecond later.
      const cutoff = Date.now() - keepDays * 86_400_000;
      let deleted = 0;
      let claimsDeleted = 0;
      db.exec('BEGIN');
      try {
        const swept = deleteClaimsForContextWhere(db, 'source = ? AND ts < ?', [
          body.source,
          cutoff,
        ]);
        claimsDeleted = swept.claimsDeleted;
        dropCachedDistillates(swept.contentHashes);
        deleted = Number(
          db.prepare('DELETE FROM context WHERE source = ? AND ts < ?').run(body.source, cutoff)
            .changes
        );
        db.exec('COMMIT');
      } catch (e) {
        db.exec('ROLLBACK');
        throw e;
      }
      send(res, 200, { deleted, claims_deleted: claimsDeleted }, cors);
      return;
    }

    if (url.pathname === '/admin/purge') {
      const body = await readJson(req);
      assertClosedFields(body, PURGE_FIELDS);
      assertKnownSource(body.source);
      let deleted = 0;
      let claimsDeleted = 0;
      db.exec('BEGIN');
      try {
        // Before the rows, not after: claim_source REFERENCES context(id) and
        // foreign_keys is on, so the other order is a constraint failure --
        // which is the design working, but a 500 is not the answer a purge
        // should give.
        const swept = deleteClaimsForContextWhere(db, 'source = ?', [body.source]);
        claimsDeleted = swept.claimsDeleted;
        dropCachedDistillates(swept.contentHashes);
        deleted = Number(db.prepare('DELETE FROM context WHERE source = ?').run(body.source).changes);
        db.exec('COMMIT');
      } catch (e) {
        db.exec('ROLLBACK');
        throw e;
      }
      // Inline and immediate, never deferred to the maintenance window: a
      // purge means "this source's data must be gone", and until the FTS
      // rebuild and VACUUM run, the deleted text is still legible in the
      // index's own pages and the file's free list. Both indexes now, because
      // a purged source's claims were legible in claim_fts by the same
      // mechanism.
      maintainNow(db);
      send(res, 200, { deleted, claims_deleted: claimsDeleted, maintained: true }, cors);
      return;
    }

    if (url.pathname === '/admin/delete-entities') {
      const body = await readJson(req);
      assertClosedFields(body, DELETE_ENTITIES_FIELDS);
      assertKnownSource(body.source);
      const ids = body.entity_ids;
      if (!Array.isArray(ids) || ids.length < 1 || ids.length > 500) {
        throw badRequest('"entity_ids" must be an array of 1 to 500 strings');
      }
      ids.forEach((id, i) => {
        if (typeof id !== 'string' || id.length === 0) {
          throw badRequest(`entity_ids[${i}] must be a non-empty string`);
        }
      });
      // Source AND entity_id must both match. Ids are namespaced by convention
      // only ("imessage:<guid>"), not by constraint — requiring the pair means
      // a connector with a crossed-up id list cannot delete another source's
      // rows.
      const del = db.prepare('DELETE FROM context WHERE source = ? AND entity_id = ?');
      let deleted = 0;
      let claimsDeleted = 0;
      db.exec('BEGIN');
      try {
        const cacheHashes = [];
        for (const id of ids) {
          const swept = deleteClaimsForContextWhere(db, 'source = ? AND entity_id = ?', [
            body.source,
            id,
          ]);
          claimsDeleted += swept.claimsDeleted;
          cacheHashes.push(...swept.contentHashes);
          deleted += Number(del.run(body.source, id).changes);
        }
        dropCachedDistillates(cacheHashes);
        db.exec('COMMIT');
      } catch (e) {
        db.exec('ROLLBACK');
        throw e;
      }
      send(res, 200, { deleted, claims_deleted: claimsDeleted }, cors);
      return;
    }

    if (url.pathname === '/admin/memory/decide') {
      const body = await readJson(req);
      send(res, 200, decideClaim(db, body), cors);
      return;
    }

    if (url.pathname === '/admin/memory/apply') {
      const body = await readJson(req);
      send(res, 200, applyMemoryBatch(db, body), cors);
      return;
    }

    if (url.pathname === '/admin/maintain') {
      const body = await readJson(req);
      assertClosedFields(body, MAINTAIN_FIELDS);
      maintainNow(db);
      send(res, 200, { maintained: true }, cors);
      return;
    }
  }

  send(res, 404, { error: `no route for ${req.method} ${url.pathname}` }, cors);
}

