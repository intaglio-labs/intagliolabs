// Small JSON body reader. Bounded so a runaway client can't balloon memory;
// the cap is per-request, sized for a batch of transcript rows.
//
// OVER-LIMIT HANDLING IS FIDDLIER THAN IT LOOKS, and two obvious versions are
// both wrong:
//
//   reject + req.destroy()  kills the socket synchronously while reject only
//                           schedules a microtask, so the 413 is written to a
//                           socket that is already gone. The caller sees
//                           ECONNRESET and cannot tell "split the batch" from
//                           "Hermes is down, retry later" -- two errors that
//                           need opposite client behaviour, which is the entire
//                           reason the status code exists.
//   reject + req.pause()    delivers the 413, but leaves the rest of the body
//                           unread. On a keep-alive socket those bytes would be
//                           parsed as the head of the next request, so the
//                           connection is unusable; a pooling client (undici,
//                           every browser) then stalls waiting for its turn.
//
// So: stop BUFFERING at the limit but keep DRAINING to 'end', and reject there.
// The response goes out on a clean, reusable connection and memory stays
// bounded by the limit rather than by the body. Past a hard multiple of the cap
// the caller is not a client that mis-sized a batch, and hanging up is the
// honest answer.
const HARD_CAP_MULTIPLE = 8;

function readJson(req, limit = 1024 * 1024) {
  return new Promise((resolve, reject) => {
    let size = 0;
    let over = false;
    let settled = false;
    let chunks = [];
    const fail = (message, status) => {
      if (settled) return;
      settled = true;
      reject(Object.assign(new Error(message), { status }));
    };
    req.on('data', (chunk) => {
      size += chunk.length;
      if (over) {
        if (size > limit * HARD_CAP_MULTIPLE) {
          fail('request body too large', 413);
          req.destroy();
        }
        return;
      }
      if (size > limit) {
        over = true;
        chunks = []; // release what was buffered; it is not going to be parsed
        return;
      }
      chunks.push(chunk);
    });
    req.on('end', () => {
      if (over) {
        fail('request body too large', 413);
        return;
      }
      if (settled) return;
      settled = true;
      try {
        resolve(JSON.parse(Buffer.concat(chunks).toString('utf8') || '{}'));
      } catch {
        reject(Object.assign(new Error('body is not valid JSON'), { status: 400 }));
      }
    });
    req.on('error', (error) => {
      if (settled) return;
      settled = true;
      reject(error);
    });
  });
}

function hasJsonMediaType(req) {
  const raw = String(req.headers['content-type'] ?? '');
  return raw.split(';', 1)[0].trim().toLowerCase() === 'application/json';
}

// Two callers, two channels, one gate. Returns the channel name, or null for
// "no recognized caller" -- which every route past /health turns into a 401.
//
//   browser  An Origin header that is PRESENT and allowlisted. A page cannot
//            forge Origin (the browser sets it), so this is a real gate on the
//            attacker CORS exists for. The page holds no secret, which is the
//            point: there is no way to hand browser JavaScript a 0600 file, and
//            inlining one through EXPO_PUBLIC_* would ship it in the bundle.
//   bearer   NO Origin header, plus a valid token from the 0600 file. This is
//            the CLI channel: seed-context, curl, Rishab's ingestion pipeline.
//
// What this replaced: `!origin || allowedOrigins.has(origin)`, which trusted
// every Origin-less caller -- and every non-browser local process sends none.
//
// Residual gap, written down so that "authenticated" does not imply more than
// it delivers: a same-machine process running as ANOTHER uid can send an
// allowlisted Origin and reach the browser channel without knowing the token.
//
// CLOSED BY DEFAULT since 2026-08-23. The allowlist is now empty unless someone
// sets HERMES_ALLOWED_ORIGINS, so on a default install there is no Origin to
// forge and this function has exactly one channel. The gap is described in the
// present tense above because it returns the moment a dev names an origin --
// which is the right trade to make deliberately, and the wrong one to inherit.
//
// A process running as THIS user is out of scope by construction: it can read
// the token file and the database directly, and no server-side check can help.
function authorize(req, { allowedOrigins, bearerToken }) {
  const origin = req.headers.origin;
  if (origin) return allowedOrigins.has(origin) ? 'browser' : null;
  // Shape first, then compare: timingSafeEqual throws on a length mismatch, and
  // the fixed-width hex pattern is what guarantees the two buffers are equal
  // length by the time it runs.
  const match = /^Bearer ([0-9a-f]{64})$/.exec(
    String(req.headers.authorization ?? '').trim()
  );
  if (!match) return null;
  let expected;
  try {
    expected = bearerToken();
  } catch {
    return null; // an unreadable or rotated-away token file fails closed
  }
  const ok = timingSafeEqual(
    Buffer.from(match[1], 'utf8'),
    Buffer.from(expected, 'utf8')
  );
  return ok ? 'bearer' : null;
}

// This server binds 127.0.0.1, but "local-only" does not stop a hostile web
// page you happen to have open from POSTing to localhost — browsers let any
// origin fire requests at 127.0.0.1 and CORS is the only gate on reading the
// response. The database is the household's private context, so reflect only
// exact configured dev origins and give every other origin nothing. Hostname-
// only checks are insufficient: any unrelated app on another localhost port
// would inherit the same access.
function corsHeaders(req, allowedOrigins) {
  const origin = req.headers.origin;
  // No Origin means no browser to satisfy, so there is nothing to reflect.
  // This is not a trust decision -- authorize() makes that one, and an
  // Origin-less caller reaches it needing a bearer token.
  if (!origin) return {};
  if (!allowedOrigins.has(origin)) return { Vary: 'Origin' };
  return {
    'Access-Control-Allow-Origin': origin,
    'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
    'Access-Control-Allow-Headers': 'Content-Type',
    Vary: 'Origin',
  };
}

const PRIVATE_RESPONSE_HEADERS = Object.freeze({
  'Cache-Control': 'no-store',
  'X-Content-Type-Options': 'nosniff',
});

// WHAT THE OWNER IS WAITING FOR, in numbers rather than a spinner.
//
// Ingesting is fast and finishing it looks like nothing happened: the rows are
// there, and the app still cannot answer, because answers come from CLAIMS and
// claims come from a distillation pass over the owner's own rows. Reporting only
// `rows` made a half-built memory look like a finished one — the state everybody
// hit was "it has full access and knows nothing", with no way to tell whether it
// was broken or busy.
//
// `done` counts rows already distilled; `pending` re-runs the real selector at
// the live watermark, so it is the actual remaining work rather than an estimate
// from a row count that includes everything the selector excludes. Counts only:
// no text crosses this boundary.
function memoryProgress(db) {
  try {
    const claims = Number(db.prepare('SELECT count(*) AS n FROM claim').get()?.n ?? 0);
    // CLAIMS ARE NOT ANSWERS UNTIL SOMEBODY SAYS SO.
    //
    // v_claim_accepted requires a claim_decision of 'accept', and retrieve.mjs
    // reads that view and nothing else — so a distilled claim nobody has reviewed
    // is invisible to every question. That is deliberate (a model's assertion is
    // not ground truth) but it was also silent: 119 claims, 0 decisions, and an
    // owner told "nothing in what i've got covers that" by a system holding 119
    // things it had written down and never asked about.
    const review = Number(
      db
        .prepare(
          'SELECT count(*) AS n FROM claim c WHERE NOT EXISTS (' +
            'SELECT 1 FROM claim_decision d WHERE d.claim_id = c.id) ' +
            // The floor, so the number the UI leads with is what the owner is
            // actually being asked about — see REVIEW_FLOOR.
            'AND (c.p_claim IS NULL OR c.p_claim >= ?)'
        )
        .get(REVIEW_FLOOR)?.n ?? 0
    );
    const accepted = Number(
      db.prepare('SELECT count(*) AS n FROM v_claim_accepted').get()?.n ?? 0
    );
    const runs = db
      .prepare(
        "SELECT count(*) AS n, " +
          "coalesce(sum(rows_in), 0) AS done, " +
          "coalesce(max(through_changed_at), 0) AS cursor " +
          "FROM distill_run WHERE status = 'complete'"
      )
      .get();
    const running = Number(
      db.prepare("SELECT count(*) AS n FROM distill_run WHERE status = 'running'").get()?.n ?? 0
    );
    // A wide window so this is "everything still to read", not "this month's".
    const pending = selectRows(db, {
      sinceChangedAt: Number(runs?.cursor ?? 0),
      fromDays: 3650,
      limit: 100000,
    }).length;
    const done = Number(runs?.done ?? 0);
    return {
      claims,
      accepted,
      review,
      runs: Number(runs?.n ?? 0),
      done,
      pending,
      total: done + pending,
      running: running > 0,
      // The one field the UI branches on, so the wording lives in one place.
      //
      // 'review' outranks 'reading' because it is the ACTIONABLE state: reading
      // proceeds on its own and needs nobody, while a review queue is the thing
      // standing between the owner and an answer. Reading progress is still in
      // the payload for the UI to say as well.
      state:
        review > 0 ? 'review' : pending > 0 ? 'reading' : done > 0 ? 'ready' : 'idle',
    };
  } catch {
    // Never let a progress read break /stats — this endpoint is also the health
    // check the widget uses to decide the backend is up at all.
    return null;
  }
}

function send(res, status, body, extraHeaders = {}) {
  res.writeHead(status, {
    ...PRIVATE_RESPONSE_HEADERS,
    'Content-Type': 'application/json; charset=utf-8',
    ...extraHeaders,
  });
  res.end(JSON.stringify(body));
}

async function proxyLlama(req, res, cors, { baseUrl, apiKey }) {
  const body = await readJson(req);
  // Read the outbound credential BEFORE the try below. Evaluated inline in the
  // headers literal it lands inside that try, and every readSecretFile message
  // -- "must not be accessible by group or other users", "file is missing; run
  // ops/setup-llm.sh" -- is discarded and replaced with "local llama-server is
  // unreachable". That names a process that was never contacted, for precisely
  // the failure the per-request re-read exists to handle: a key rotation that
  // lands the file at the wrong mode against a running Hermes. The operator
  // then restarts and debugs a launchd service that was never the problem.
  // Thrown here, it reaches the generic handler and says what is actually wrong.
  const key = apiKey();
  const abort = new AbortController();
  const clientClosed = () => {
    if (!res.writableEnded) abort.abort();
  };
  res.once('close', clientClosed);

  let upstream;
  try {
    upstream = await fetch(`${baseUrl}/v1/chat/completions`, {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${key}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify(body),
      signal: abort.signal,
      // A compromised or misconfigured loopback service must not redirect a
      // household prompt (or its Authorization header) onto the network.
      redirect: 'error',
    });
  } catch (error) {
    res.off('close', clientClosed);
    if (abort.signal.aborted) return;
    throw Object.assign(new Error('local llama-server is unreachable'), { status: 502 });
  }

  if (!upstream.ok) {
    res.off('close', clientClosed);
    await upstream.body?.cancel().catch(() => {});
    send(res, 502, { error: 'local llama-server rejected the request' }, cors);
    return;
  }
  if (!upstream.body) {
    res.off('close', clientClosed);
    send(res, 502, { error: 'local llama-server returned no response body' }, cors);
    return;
  }

  res.writeHead(200, {
    ...PRIVATE_RESPONSE_HEADERS,
    ...cors,
    'Content-Type': upstream.headers.get('content-type') || 'text/event-stream; charset=utf-8',
  });
  try {
    await pipeline(Readable.fromWeb(upstream.body), res);
  } catch (error) {
    abort.abort();
    if (!res.destroyed) res.destroy(error);
  } finally {
    res.off('close', clientClosed);
  }
}

